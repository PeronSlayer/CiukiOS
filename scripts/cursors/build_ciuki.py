#!/usr/bin/env python3
"""Rasterise the original CiukiOS SVG cursor sources; no downloads or fonts.

The committed output is the build input. --check verifies it without edits.
Dependencies: rsvg-convert (librsvg) and Pillow; see assets/cursors/README.md.
"""
# SPDX-License-Identifier: GPL-2.0-only
import argparse
import io
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "assets/cursors/ciuki"
NAMES = ("arrow", "busy", "arrow_busy", "text", "forbidden", "resize_ew",
         "resize_ns", "resize_nwse", "resize_nesw", "move", "hand", "crosshair",
         "precision", "open_hand", "closed_hand", "help",
         "drag_move", "drag_copy", "drag_link")


def raster(name):
    svg = SOURCE / (name + ".svg")
    root = ET.parse(svg).getroot()
    hot = tuple(int(root.attrib["data-hot-" + axis]) for axis in ("x", "y"))
    if root.attrib.get("viewBox") != "0 0 32 32" or not all(0 <= p < 32 for p in hot):
        raise ValueError(f"invalid canvas/hotspot: {svg}")
    png = subprocess.run(["rsvg-convert", "--width=32", "--height=32", str(svg)],
                         check=True, capture_output=True).stdout
    pixels = Image.open(io.BytesIO(png)).convert("RGBA")
    mask, image = [], []
    for y in range(32):
        m = v = 0
        for x in range(32):
            r, g, b, a = pixels.getpixel((x, y))
            if a >= 128:
                m |= 1 << (31-x)
                if r+g+b >= 3*128:
                    v |= 1 << (31-x)
        mask.append(m)
        image.append(v)
    if not any(mask):
        raise ValueError(f"empty cursor: {svg}")
    # Integer separable [1,2,1] blur, offset (1,1), peak opacity 80/255.
    # No floating point, font, colour-profile or image-library blur involved.
    shadow = []
    for y in range(32):
        for x in range(32):
            weight = 0
            for ky, wy in enumerate((1, 2, 1)):
                for kx, wx in enumerate((1, 2, 1)):
                    sx, sy = x+kx-2, y+ky-2
                    if 0 <= sx < 32 and 0 <= sy < 32 and mask[sy] & (1 << (31-sx)):
                        weight += wx*wy
            shadow.append(0 if mask[y] & (1 << (31-x)) else weight*5)
    points = [(x, y) for y in range(32) for x in range(32)
              if mask[y] & (1 << (31-x)) or shadow[y*32+x]]
    width, height = max(x for x, y in points)+1, max(y for x, y in points)+1
    return hot, width, height, mask, image, shadow


def header():
    rows = [raster(name) for name in NAMES]
    lines = ["/* SPDX-License-Identifier: GPL-2.0-only */",
             "/* Original CiukiOS artwork; generated by scripts/cursors/build_ciuki.py. */",
             "#ifndef CIUKI_CURSOR_RASTERS_H", "#define CIUKI_CURSOR_RASTERS_H",
             "#include <stdint.h>",
             "struct desk_cursor_raster { unsigned hot_x, hot_y, width, height; uint32_t mask[32], image[32]; const uint8_t *shadow; };"]
    for name, row in zip(NAMES, rows):
        lines.append(f"static const uint8_t desk_shadow_{name}[32*32] = {{")
        lines += ["    " + ",".join(str(v) for v in row[5][y*32:(y+1)*32]) + "," for y in range(32)]
        lines.append("};")
    for array, start, end in (("desk_cursors", 0, 13), ("desk_extra_cursors", 13, 19)):
        lines.append(f"static const struct desk_cursor_raster {array}[] = {{")
        for name, (hot, w, h, mask, image, _) in zip(NAMES[start:end], rows[start:end]):
            lines += [f"    /* {name} */", f"    {{{hot[0]}, {hot[1]}, {w}, {h}, {{"]
            for plane in (mask, image):
                lines += ["        " + ", ".join(f"0x{v:08x}u" for v in plane[y:y+4]) + "," for y in range(0, 32, 4)]
                if plane is mask:
                    lines.append("    }, {")
            lines.append(f"    }}, desk_shadow_{name}}},")
        lines.append("};")
    return "\n".join([*lines, "#endif", ""])


def sheet(path):
    """Review aid: hardware silhouette and software shadow at 2x scale."""
    result = Image.new("RGB", (640, (len(NAMES)+3)//4*144), "#e8e8e8")
    draw = ImageDraw.Draw(result)
    for i, name in enumerate(NAMES):
        hot, _, _, mask, image, shadow = raster(name)
        for mode in range(2):
            tile = Image.new("RGB", (32, 32), "#c8d8e8")
            for y in range(32):
                for x in range(32):
                    bit = 1 << (31-x)
                    if mask[y] & bit:
                        tile.putpixel((x, y), (255,)*3 if image[y] & bit else (0,)*3)
                    elif mode:
                        a = shadow[y*32+x]
                        tile.putpixel((x, y), tuple((v*(255-a)+127)//255 for v in (200,216,232)))
            result.paste(tile.resize((64, 64), Image.Resampling.NEAREST), (i%4*160+mode*72, i//4*144+4))
        draw.text((i%4*160+4, i//4*144+76), name, fill="black")
        draw.text((i%4*160+4, i//4*144+94), f"hotspot {hot[0]},{hot[1]}", fill="black")
        draw.text((i%4*160+4, i//4*144+112), "HW / software", fill="black")
    path.parent.mkdir(parents=True, exist_ok=True)
    result.save(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=ROOT / "assets/cursors/cursors.h")
    parser.add_argument("--sheet", type=Path)
    args = parser.parse_args()
    text = header()
    if args.check:
        if args.output.read_text() != text:
            raise SystemExit("cursor header differs: regenerate with scripts/cursors/build_ciuki.py")
        print("PASS original cursor SVGs reproduce the committed header")
    else:
        args.output.write_text(text)
    if args.sheet:
        sheet(args.sheet)


if __name__ == "__main__":
    main()
