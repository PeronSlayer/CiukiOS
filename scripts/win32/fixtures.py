ROOT = Path(__file__).resolve().parents[2]
SOURCES = ROOT/'tests/host/win32/fixtures'
O = 0x98
TABLE = O+224


def put(data, off, value, width=4):
    struct.pack_into({2: '<H', 4: '<I'}[width], data, off, value)


def template():
    data = bytearray(0x2400)
    data[:2] = b'MZ'
    put(data, 60, 0x80)
    data[0x80:0x84] = b'PE\0\0'
    struct.pack_into('<HHIIIHH', data, 0x84, 0x14c, 2, 0, 0, 0, 224, 0x102)
    put(data, O, 0x10b, 2)
    data[O+2:O+4] = bytes([23, 1])
    for off, value in ((4,512),(8,8192),(16,0x1000),(20,0x1000),(24,0x2000),
                       (28,0x400000),(32,4096),(36,512),(56,0x4000),(60,512),
                       (72,0x100000),(76,4096),(80,0x100000),(84,4096),(92,16)):
        put(data, O+off, value)
    put(data, O+40, 4, 2)
    put(data, O+48, 4, 2)
    put(data, O+68, 3, 2)
    struct.pack_into('<8sIIIIIIHHI', data, TABLE, b'.text', 512, 0x1000,
                     512,512,0,0,0,0,0x60000020)
    struct.pack_into('<8sIIIIIIHHI', data, TABLE+40, b'.data', 8192,0x2000,
                     8192,1024,0,0,0,0,0xc0000040)
    # Return an absolute pointer, giving relocation fixtures a real HIGHLOW site.
    data[512:518] = b'\xb8\x00\x20\x40\x00\xc3'
    return data


def synthetic(spec):
    data = template()
    def at(r):
        return r-0x2000+0x400
    def words(r, *v):
        struct.pack_into('<'+'I'*len(v), data, at(r), *v)
    def directory(i, r, n):
        put(data, O+96+i*8, r)
        put(data, O+100+i*8, n)
    def string(r, text):
        raw = text.encode('ascii')+b'\0'
        data[at(r):at(r)+len(raw)] = raw
    features = spec.get('features', [])
    if any(f in features for f in ('import-name','import-ordinal','import-mixed','iat-fallback','bound','bound-no-names')):
        directory(1,0x2000,40)
        words(0x2000, 0 if 'iat-fallback' in features or 'bound-no-names' in features else 0x2100,
              123 if 'bound' in features or 'bound-no-names' in features else 0, 0,0x2080,0x2120)
        string(0x2080, spec.get('dll', 'provider.dll'))
        values = [0x2140]
        if 'import-ordinal' in features:
            values = [0x8000000b]
        if 'import-mixed' in features:
            values += [0x8000000b]
        if 'bound-no-names' in features:
            values = [0x70123456]
        words(0x2100,*values,0)
        words(0x2120,*([0x70123456] if 'bound' in features else values),0)
        string(0x2142,spec.get('symbol','FixtureValue'))
    if 'bound' in features or 'bound-no-names' in features:
        directory(11,0x2400,128)
        struct.pack_into('<IHH',data,at(0x2400),123,32,1)
        struct.pack_into('<IHH',data,at(0x2408),456,48,0)
        string(0x2420,'provider.dll')
        string(0x2430,'forward.dll')
    if 'delay' in features or 'delay-va' in features:
        directory(13,0x2500,64)
        va = 'delay-va' in features
        add = 0x400000 if va else 0
        words(0x2500,0 if va else 1,0x2080+add,0x2690+add,0x2120+add,0x2100+add,0,0,0)
        string(0x2080,'provider.dll')
        words(0x2100,0x2140+add,0x8000000b,0)
        words(0x2120,0x2140+add,0x8000000b,0)
        string(0x2142,'FixtureValue')
    if 'exports' in features or 'forward-name' in features or 'forward-ordinal' in features or 'forward-cycle' in features or 'export-data' in features:
        directory(0,0x2200,256)
        words(0x2200,0,0,0,0x2300,7,2,1,0x2240,0x2250,0x2260)
        addr = 0x2000 if 'export-data' in features else 0x1000
        if any(f.startswith('forward-') for f in features):
            addr = 0x22a0
            string(addr, spec.get('forwarder', 'provider.#11' if 'forward-ordinal' in features else
                   ('fixture.FixtureValue' if 'forward-cycle' in features else 'provider.FixtureValue')))
        words(0x2240,addr,0)  # second ordinal is a hole
        words(0x2250,0x2290)
        string(0x2300,spec['id']+'.dll')
        string(0x2290,'FixtureValue')
    if 'tls' in features or 'tls-two' in features or 'tls-empty' in features:
        directory(9,0x2600,24)
        words(0x2600,0x402680,0x402684,0x402690,0x402640,8,0)
        cb = [] if 'tls-empty' in features else [0x401000]
        if 'tls-two' in features:
            cb += [0x401000]
        words(0x2640,*cb,0)
        data[at(0x2680):at(0x2680)+4] = b'\x01\x02\x03\x04'
    if 'reloc' in features or 'reloc-highadj' in features:
        directory(5,0x2700,12)
        words(0x2700,0x1000,12)
        struct.pack_into('<HH',data,at(0x2708),0x4001 if 'reloc-highadj' in features else 0x3001,0)
    if any(f.startswith('resource') for f in features) or 'manifest' in features:
        directory(2,0x2800,1024)
        typ = 24 if 'manifest' in features else 10
        lang = 1040 if 'resource-italian' in features else 1033
        for rel in (0,24,48):
            struct.pack_into('<HH', data, at(0x2800+rel)+12,1 if rel==24 and 'resource-named' in features else 0,
                             0 if rel==24 and 'resource-named' in features else 1)
        words(0x2810,typ,0x80000018)
        words(0x2828,0x80000060 if 'resource-named' in features else 1,0x80000030)
        words(0x2840,lang,72)
        payload = (b'<assembly xmlns="urn:schemas-microsoft-com:asm.v1"><assemblyIdentity '
                   b'name="Ciuki.Fixture" version="1.0.0.0" processorArchitecture="x86"/></assembly>') if 'manifest' in features else b'fixture-data'
        words(0x2848,0x2900,len(payload),0,0)
        data[at(0x2900):at(0x2900)+len(payload)] = payload
        named = 'HELLO'.encode('utf-16le')
        struct.pack_into('<H',data,at(0x2860),5)
        data[at(0x2862):at(0x2862)+len(named)] = named
    if 'dll' in features:
        put(data,0x96,0x2102,2)
    if 'gui' in features:
        put(data,O+68,2,2)
    if 'no-reloc' in features:
        put(data,0x96,struct.unpack_from('<H',data,0x96)[0] | 1,2)
    if 'rwx' in features:
        put(data,TABLE+36,0xe0000020)
    if 'packer-name' in features:
        data[TABLE:TABLE+8] = b'UPX0\0\0\0\0'
    if 'low-alignment' in features:
        for off in (32,36): put(data,O+off,512)
        put(data,O+16,512)
        put(data,O+56,0x2400)
        put(data,TABLE+12,512)
        put(data,TABLE+52,1024)
    for patch in spec.get('patches', []):
        put(data,patch['offset'],patch['value'],patch.get('width',4))
    if 'truncate' in spec:
        data = data[:spec['truncate']]
    if 'certificate' in features:
        off = len(data)
        data.extend(struct.pack('<IHH',8,0x200,2))
        directory(4,off,8)
    return bytes(data)


def command(args, out):
    env = dict(os.environ, SOURCE_DATE_EPOCH='0', TMPDIR=str(out.resolve()), LC_ALL='C')
    p = subprocess.run([str(a) for a in args], text=True, capture_output=True,
                       cwd=SOURCES, env=env, timeout=30)
    if p.returncode:
        raise RuntimeError(' '.join(map(str,args))+'\n'+p.stdout+p.stderr)


def compiled(spec, out):
    name = spec['id']
    obj = out/(name+'.obj')
    target = spec.get('target', 'i686-pc-windows-msvc')
    source = SOURCES/spec['source']
    flags = ['--target='+target,'-march=pentiumpro','-ffreestanding','-fno-stack-protector',
             '-fno-ident','-O0']
    if source.suffix == '.s': flags += ['-x','assembler-with-cpp']
    flags += ['-D'+d for d in spec.get('defines', [])]
    command(['clang',*flags,'-c',source,'-o',obj],out)
    path = out/(name+('.dll' if spec.get('dll') else '.exe'))
    entry = 'DllMain@12' if spec.get('dll') else 'entry'
    link = ['lld-link','/machine:x86','/nodefaultlib','/entry:'+entry,
            '/subsystem:'+spec.get('subsystem','console')+',4.0','/osversion:4.0',
            '/timestamp:0','/incremental:no',
            '/safeseh:no','/out:'+str(path),obj]
    if spec.get('dll'):
        link += ['/dll','/implib:'+str(out/(name+'.lib'))]
    if spec.get('exports'):
        link += ['/def:'+str(SOURCES/'provider.def')]
    if spec.get('imports'):
        lib = out/'provider-import.lib'
        if not lib.exists():
            command(['llvm-dlltool','-m','i386','-d',SOURCES/'provider.def','-l',lib],out)
        link += [lib]
    if spec.get('builtin_imports'):
        lib = out/'kernel32-import.lib'
        command(['llvm-dlltool','-m','i386','-k','-d',SOURCES/'kernel32.def','-l',lib],out)
        link += [lib]
    if spec.get('resources'):
        res = out/(name+'.res')
        command(['llvm-rc','/fo',res,SOURCES/'resources.rc'],out)
        link += [res]
    if spec.get('source') == 'packed.s': link += ['/section:.text,ERW']
    command(link,out)
    return path


def manifests():
    specs = json.loads((SOURCES/'corpus.json').read_text())
    require_ids = [s['id'] for s in specs]
    if len(set(require_ids)) != len(specs) or len(specs) < 60:
        raise ValueError('corpus needs at least 60 unique fixture IDs')
    for spec in specs:
        if (not re.fullmatch(r'[a-z0-9][a-z0-9-]*', spec['id']) or
            spec['kind'] not in ('synthetic','compiled') or not spec['rules'] or
            not all(isinstance(rule,str) for rule in spec['rules']) or
            not isinstance(spec['runtime'],str) or not spec['runtime'] or
            'pending' not in spec['evidence']):
            raise ValueError('incomplete manifest: '+spec['id'])
        if 'census' not in spec or ('error' not in spec['census'] and 'imports' not in spec['census']):
            raise ValueError('missing independently authored census oracle: '+spec['id'])
        if 'error' in spec['census'] and (not spec['census']['error'] or spec.get('guest_error') != 193):
            raise ValueError('missing refusal reason/Windows error: '+spec['id'])
        if spec['kind'] == 'compiled' and (Path(spec['source']).name != spec['source'] or
                                         not (SOURCES/spec['source']).is_file()):
            raise ValueError('compiled source outside fixture directory: '+spec['id'])
    return specs


def build(out, check_pins=True):
    out = Path(out).resolve()
    if not out.is_relative_to((ROOT/'build/host/win32').resolve()):
        raise ValueError('fixture output must be under build/host/win32')
    if check_pins:
        _, errors, _ = toolchain.verify(probe=False)
        if errors:
            raise RuntimeError('\n'.join(errors))
    out.mkdir(parents=True,exist_ok=True)
    hashes = {}
    for spec in manifests():
        if spec['kind'] == 'synthetic':
            path = out/(spec['id']+('.dll' if 'dll' in spec.get('features',[]) else '.exe'))
            path.write_bytes(synthetic(spec))
        else:
            path = compiled(spec,out)
        hashes[path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
    (out/'hashes.json').write_text(json.dumps(hashes,sort_keys=True,indent=2)+'\n')
    return hashes


def census_text(out):
    hashes = json.loads((Path(out)/'hashes.json').read_text())
    chunks = ['# f5-02A self-authored corpus; static host evidence only.\n\n']
    for name, digest in sorted(hashes.items()):
        try:
            chunks.append(census.format_text(name,digest,census.inspect((Path(out)/name).read_bytes())))
        except census.PEError as e:
            chunks.append(census.format_text(name,digest,error=str(e)))
    return ''.join(chunks)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--output',type=Path,default=ROOT/'build/host/win32/current')
    ap.add_argument('--census',type=Path,help='write metadata text census')
    args = ap.parse_args()
    hashes = build(args.output)
    if args.census:
        args.census.write_text(census_text(args.output))
    print(f'Built {len(hashes)} PE fixtures under {args.output}')


if __name__ == '__main__':
    raise SystemExit(main())
