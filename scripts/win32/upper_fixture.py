"""f5-20D: the w32-upper-dlls guest fixture (one authored PE, selected at run time).

src/probes/win32_upper/exercise.c becomes /System/Win32/Fixtures/upper-exercise.exe.
Its table of reused Wine DLLs is generated from the qualified entries of
config/wine-upper.json (name and manifest base, lowest base first), so the
fixture follows the staged set: it neither needs the upper build nor changes
unless the record does. The kernel probe reads its result block (controller.h).
No image variant, no guest run here."""
# SPDX-License-Identifier: LGPL-2.1-or-later
import json
from pathlib import Path
import re
import subprocess
import sys
ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from scripts.win32 import gdi32

SOURCE = ROOT/'src/probes/win32_upper'
RECORD = ROOT/'config/wine-upper.json'
NAME = 'upper-exercise.exe'


def staged_table(record=None):
    """[(name, base)] of the qualified reused DLLs, lowest manifest base first."""
    record = record or json.loads(RECORD.read_text())
    rows = sorted((r['base'], n) for n, r in record['dlls'].items() if r['qualified'])
    return [(n, b) for b, n in rows]


def table_header(table):
    return ('/* Generated by scripts/win32/upper_fixture.py from config/wine-upper.json (qualified entries). */\n'
            'static const struct w32_upper_entry W32_UPPER_TABLE[] = {\n' +
            ''.join(f'    {{"{n}", 0x{b:08x}u}},\n' for n, b in table) +
            '};\n'
            '#define W32_UPPER_TABLE_COUNT ((uint32_t)(sizeof(W32_UPPER_TABLE) / sizeof(W32_UPPER_TABLE[0])))\n'
            f'_Static_assert({len(table)} <= W32_UPPER_MAX, "w32-upper-dlls table exceeds the result block");\n')


def imports(obj):
    """Undefined stdcall symbols of the object (all KERNEL32)."""
    names = subprocess.run(['llvm-nm', '-u', str(obj)], check=True, capture_output=True, text=True).stdout
    found = re.findall(r'\bU _([A-Za-z][A-Za-z0-9_]*)@(\d+)\s*$', names, re.M)
    leftover = [l for l in names.split() if l not in ('U',) and not re.fullmatch(r'_[A-Za-z][A-Za-z0-9_]*@\d+', l)]
    if leftover:
        raise ValueError('upper fixture has non-stdcall imports: ' + str(leftover))
    return sorted(f'{name}@{arity}' for name, arity in found)


def resolve(image, dlls):
    """Every import of the fixture must be a real export of the built KERNEL32."""
    from scripts.win32 import census
    info = census.inspect(Path(image).read_bytes())
    exports = {n for row in census.inspect((Path(dlls)/'kernel32.dll').read_bytes())['exports'] for n in row['names']}
    missing = [f"{row['dll']}!{name}" for row in info['imports'] for name in row['symbols']
               if row['dll'].lower() != 'kernel32.dll' or name not in exports]
    if missing:
        raise ValueError('upper fixture imports missing exports: ' + ', '.join(missing))


def build(out, dlls=None, record=None):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    table = staged_table(record)
    if not table:
        raise ValueError('no qualified reused Wine DLL in config/wine-upper.json: nothing for the fixture to load')
    (out/'upper_table.h').write_text(table_header(table))
    flags = [*gdi32.FLAGS, '-I'+str(ROOT/'sdk/win32/include'), '-I'+str(ROOT/'src/kernel/include'), '-I'+str(out)]
    obj = out/'upper-exercise.obj'
    subprocess.run(['clang', *flags, '-c', str(SOURCE/'exercise.c'), '-o', str(obj)], check=True)
    definition = out/'upper-kernel32.def'
    definition.write_text('LIBRARY kernel32.dll\nEXPORTS\n'+''.join(f' {n}\n' for n in imports(obj)))
    library = definition.with_suffix('.lib')
    subprocess.run(['llvm-dlltool', '-m', 'i386', '-k', '-d', str(definition), '-l', str(library)], check=True)
    image = out/NAME
    subprocess.run(['lld-link', '/machine:x86', '/entry:entry@0', '/nodefaultlib', '/safeseh:no', '/timestamp:0',
                    '/incremental:no', '/base:0x00400000', '/subsystem:windows,4.0', '/osversion:4.0',
                    '/out:'+str(image), str(obj), str(library)], check=True)
    if dlls:
        resolve(image, dlls)
    return image


if __name__ == '__main__':
    print(build(ROOT/'build/host/win32/upper-fixture'))
