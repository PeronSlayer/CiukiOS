#!/usr/bin/env python3
"""Deterministic native API reference from public header comments/declarations."""
# SPDX-License-Identifier: MIT
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = ROOT / "docs/developer-api.md"


def headers(root=ROOT):
    result = {"ciuki/" + p.name: p for p in sorted((root / "sdk/sysroot-overlay/include/ciuki").glob("*.h"))}
    result["ciuki/abi.h"] = root / "src/kernel/include/ciuki/abi.h"
    for name in ("tzrule.h", "tzdata.h"):  # G1: installed into the SDK by build_sdk.py
        result["ciuki/" + name] = root / "src/kernel/include/ciuki" / name
    result["ciuki/desktop.h"] = root / "apps/desktop/protocol.h"
    # f7-14: the native OpenGL binding (backend policy, accounting, lease
    # presentation); GL/gl.h itself is the generated OpenGL 1.1 declaration list.
    result["ciuki/gl.h"] = root / "sdk/libgl/include/ciuki/gl.h"
    result["deskui.h"] = root / "apps/libdeskui/deskui.h"
    result["deskui/v3.h"] = root / "apps/libdeskui/v3.h"
    result["deskui/textarea.h"] = root / "apps/libdeskui/textarea.h"
    for name in ("setup_txn.h", "setup_inf.h"):
        result[name] = root / "sdk/libsetup/include" / name
    return dict(sorted(result.items()))


def header_reference(name, path):
    text = path.read_text()
    # Compile-time record-layout assertions are checks, not API declarations.
    text = re.sub(r"_Static_assert\(.*?;", "", text, flags=re.S)
    blocks = [f"## `{name}`\n", f"Source: `{path.relative_to(ROOT)}`.\n"]
    for i, part in enumerate(re.split(r"(/\*.*?\*/)", text, flags=re.S)):
        if not part.strip():
            continue
        if part.startswith("/*"):
            comment = re.sub(r"^\s*\* ?", "", part[2:-2], flags=re.M).strip()
            if comment:
                blocks.append(comment + "\n")
        else:
            # Keep conditional compilation visible: these are actual header
            # declarations, not inferred prototypes or guessed API promises.
            blocks.append("```c\n" + part.strip() + "\n```\n")
    return "\n".join(blocks)


def generate():
    return "# CiukiOS native API reference\n\nGenerated by `scripts/gen_api_reference.py`; edit the public headers, then regenerate.\n\n" + "\n".join(
        header_reference(n, p) for n, p in headers().items())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not args.output.is_file() or args.output.read_text() != expected:
            parser.error("API reference is stale; run scripts/gen_api_reference.py")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected)


if __name__ == "__main__":
    main()
