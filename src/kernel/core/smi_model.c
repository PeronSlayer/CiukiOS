/* f1-94: pure SMI attribution and mitigation decisions; no I/O.
 * Sources (290716-001 = Intel 82801CAM ICH3-M datasheet):
 * - 9.8.3.14 SMI_EN: defined enables 0-6, 11, 13, 14; BIOS_RLS (7) is
 *   write-only and a 1 raises an SCI; EOS (1) re-arms the SMI arbiter.
 * - 9.8.3.15 SMI_STS: "If the corresponding _EN bit is set when the _STS bit
 *   is set, the ICH3 will cause an SMI# (except bits 8-10 and 12, which don't
 *   need enable bits since they are logic ORs of other registers that have
 *   enable bits)"; SERIRQ_SMI_STS (15) and SMBUS_SMI_STS (16) have no
 *   SMI_EN enable; TCO_STS (13) is read-only and also reports re-routed NMIs.
 * - 9.8.3.15 bit 3: LEGACY_USB_STS "will not be active if the enable bits
 *   are not set" (the USB_LEGKEY enables of 11.1.16).
 * - 9.8.3.14 bit 0: GBL_SMI_EN 0 means "No SMI# will be generated by ICH3".
 * Decisions per bit: docs/validation/f1-94-irqoff-blackout.md.
 * SPDX-License-Identifier: GPL-2.0-only */
#include <ciuki/smi.h>

#define ICH3M_EN_RW  (SMI_EN_GBL | SMI_EN_EOS | SMI_EN_BIOS | SMI_EN_LEGACY_USB | SMI_EN_SLP | \
                      SMI_EN_APMC | SMI_EN_SWSMI_TMR | SMI_EN_MCSMI | SMI_EN_TCO | SMI_EN_PERIODIC)
#define ICH3M_STS    (SMI_STS_BIOS | SMI_STS_LEGACY_USB | SMI_STS_SLP | SMI_STS_APM | \
                      SMI_STS_SWSMI_TMR | SMI_STS_PM1 | SMI_STS_GPE0 | SMI_STS_GPE1 | \
                      SMI_STS_MCSMI | SMI_STS_DEVMON | SMI_STS_TCO | SMI_STS_PERIODIC | \
                      SMI_STS_SERIRQ | SMI_STS_SMBUS)
/* Only the chipset whose datasheet was checked bit by bit and whose SMI_EN
 * value was read on the owner's hardware (T23: 0000402b). Other ICH parts
 * differ (ICH4 adds USB 2.0 enables at bits 17/18); they stay unsupported
 * until their own datasheet is checked, exactly like registry_smi_snapshot. */
static const struct smi_chipset chipsets[] = {
    { 0x248c8086u, "ICH3-M", ICH3M_EN_RW, ICH3M_STS, 7, {0x2482, 0x2484, 0x2487}, true },
};

const struct smi_chipset *smi_chipset(uint32_t lpc_id)
{
    for (unsigned i = 0; i < sizeof(chipsets) / sizeof(chipsets[0]); i++)
        if (chipsets[i].lpc_id == lpc_id) return &chipsets[i];
    return 0;
}

uint32_t smi_causal_status(const struct smi_chipset *c, uint32_t en)
{
    if (!c || !(en & SMI_EN_GBL)) return 0;
    uint32_t causal = SMI_STS_PM1 | SMI_STS_GPE0 | SMI_STS_GPE1 | SMI_STS_DEVMON |
                      SMI_STS_TCO | SMI_STS_SERIRQ | SMI_STS_SMBUS;
    static const uint32_t gated[][2] = {
        { SMI_EN_BIOS, SMI_STS_BIOS }, { SMI_EN_LEGACY_USB, SMI_STS_LEGACY_USB },
        { SMI_EN_SLP, SMI_STS_SLP }, { SMI_EN_APMC, SMI_STS_APM },
        { SMI_EN_SWSMI_TMR, SMI_STS_SWSMI_TMR }, { SMI_EN_MCSMI, SMI_STS_MCSMI },
        { SMI_EN_PERIODIC, SMI_STS_PERIODIC },
    };
    for (unsigned i = 0; i < sizeof(gated) / sizeof(gated[0]); i++)
        if (en & gated[i][0]) causal |= gated[i][1];
    return causal & c->sts_defined;
}

const char *smi_reason_name(enum smi_reason r)
{
    static const char *const names[] = { "clear", "unqualified_chipset", "diagnostic_boot",
        "smi_disabled", "not_armed", "usb_incomplete", "usb_not_owned", "legkey_armed" };
    return (unsigned)r < sizeof(names) / sizeof(names[0]) ? names[r] : "unknown";
}

struct smi_plan smi_mitigation_plan(const struct smi_chipset *c, uint32_t en,
    unsigned uhci_present, unsigned uhci_owned, const uint16_t legkey[3], bool allowed)
{
    struct smi_plan p = { 0, 0, SMI_PLAN_UNQUALIFIED };
    if (!c || !c->qualified) return p;
    /* Everything enabled stays with the firmware unless proven ours below. */
    p.kept = en & c->en_rw & ~(SMI_EN_EOS | SMI_EN_BIOS_RLS);
    if (!allowed) { p.reason = SMI_PLAN_DIAGNOSTIC; return p; }
    if (!(en & SMI_EN_GBL)) { p.reason = SMI_PLAN_GLOBAL_OFF; return p; }
    if (!(en & SMI_EN_LEGACY_USB)) { p.reason = SMI_PLAN_NOT_ARMED; return p; }
    /* The legacy-USB SMI belongs to the UHCI functions. All of them must be
     * present and owned by the native driver: the LEGKEY trap enables are
     * OR'ed across the functions (11.1.16), one BIOS-owned function keeps
     * the source alive. */
    if ((uhci_present & c->uhci_functions) != c->uhci_functions) {
        p.reason = SMI_PLAN_USB_INCOMPLETE; return p;
    }
    if ((uhci_owned & c->uhci_functions) != c->uhci_functions) {
        p.reason = SMI_PLAN_USB_NOT_OWNED; return p;
    }
    for (unsigned i = 0; i < 3; i++)
        if ((c->uhci_functions & (1u << i)) && (legkey[i] & SMI_LEGKEY_ARMED)) {
            p.reason = SMI_PLAN_LEGKEY_ARMED; return p;
        }
    p.clear = SMI_EN_LEGACY_USB;
    p.kept &= ~SMI_EN_LEGACY_USB;
    p.reason = SMI_PLAN_CLEAR;
    return p;
}

enum smi_class smi_classify(const struct smi_chipset *c, const struct smi_sample *s,
                            uint64_t per_ms, uint32_t *sources)
{
    const struct smi_section *x = &s->section;
    *sources = 0;
    if (!per_ms || x->end <= x->start) return SMI_CLASS_NONE;
    uint64_t d = x->end - x->start, minimum = per_ms * SMI_GAP_MIN_US / 1000u;
    if (d < minimum) return SMI_CLASS_NONE;
    if (c && s->before_valid) {
        uint32_t rise = s->after & ~s->before & smi_causal_status(c, s->en);
        if (rise) { *sources = rise; return SMI_CLASS_STATUS; }
    }
    /* The gap lies between two consecutive marks of straight-line code: no
     * work there can take a millisecond. It must also dominate the section,
     * so the remaining (executed) work is the smaller part. */
    if (x->gap_bounded && x->gap >= minimum && x->gap_start >= x->start &&
        x->gap <= x->end - x->gap_start && x->gap > d - x->gap)
        return SMI_CLASS_TSC;
    return SMI_CLASS_UNPROVEN;
}
