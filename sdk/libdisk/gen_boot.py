#!/usr/bin/env python3
"""Assemble the incomplete-install and canonical MBR code for libdisk.

f9-02: src/boot/setup_stub_mbr.asm and src/boot/mbr.asm are assembled with
nasm; their first 440 bytes (code only: the disk signature, partition table
and 55AA are written by libdisk from the plan) become a C source compiled
into libdisk.a. --manifest records the sources and code digests for the SDK
manifest. Used by sdk/build_sdk.py and scripts/test/host_fs_tests.sh.
"""
# SPDX-License-Identifier: MIT
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCES = (("disk_stub_mbr_code", "src/boot/setup_stub_mbr.asm"),
           ("disk_canonical_mbr_code", "src/boot/mbr.asm"))


def assemble(nasm, source, scratch):
    out = Path(scratch) / (Path(source).stem + ".bin")
    subprocess.run([nasm, "-f", "bin", str(ROOT / source), "-o", str(out)], check=True)
    data = out.read_bytes()
    if len(data) != 512 or data[510:] != b"\x55\xaa" or any(data[440:510]):
        raise SystemExit(f"{source}: expected 440 code bytes, empty signature/table and 55AA")
    return data


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True, help="generated C source")
    ap.add_argument("--nasm", default="nasm")
    ap.add_argument("--manifest", type=Path)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by sdk/libdisk/gen_boot.py from GPL-2.0-only boot sources; do not edit. */",
             "#include <libdisk.h>"]
    record = {}
    with tempfile.TemporaryDirectory(dir=args.out.parent) as scratch:
        for name, source in SOURCES:
            code = assemble(args.nasm, source, scratch)[:440]
            body = ",".join(f"0x{b:02x}" for b in code)
            lines.append(f"const uint8_t {name}[440] = {{{body}}};")
            record[name] = {"source": source,
                            "source_sha256": hashlib.sha256((ROOT / source).read_bytes()).hexdigest(),
                            "code_sha256": hashlib.sha256(code).hexdigest(),
                            "license": "GPL-2.0-only"}
    args.out.write_text("\n".join(lines) + "\n")
    if args.manifest:
        args.manifest.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
