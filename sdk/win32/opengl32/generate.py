"""Generate only mechanical stdcall forwarding and numeric GL overloads."""
# SPDX-License-Identifier: MIT
import json
from pathlib import Path
import re
HERE=Path(__file__).resolve().parent
rows=json.loads((HERE/'abi.json').read_text())['functions']+json.loads((HERE/'extensions.json').read_text())
code=['/* Generated by generate.py; no renderer semantics here. */','#include "internal.h"']
ids=[];family=[];vectors=[];validation=[]
types={'b':'GLbyte','ub':'GLubyte','s':'GLshort','us':'GLushort','i':'GLint','ui':'GLuint','f':'GLfloat','d':'GLdouble'}
scales={'b':'127.0','ub':'255.0','s':'32767.0','us':'65535.0','i':'2147483647.0','ui':'4294967295.0'}
for idx,row in enumerate(rows):
 name,ret,args=(row[k] for k in ('name','return','args'));ids.append(f' ID_{name}={idx},')
 params=[]
 if args.strip() and args!='void':
  for arg in args.split(','):
   arg=arg.strip();param=re.search(r'(\w+)$',arg)[1];field='p' if '*' in arg else 'f' if any(t in arg for t in ('GLfloat','GLdouble')) else 'i';params.append('{.'+field+'='+param+'}')
 code.append(f'{ret} W32API w32_{name}({args}){{union gl_arg call_args[12]={{'+(','.join(params) if params else '{.i=0}')+'};union gl_arg call_result=w32_gl_dispatch(ID_'+name+',call_args);'+('(void)call_result;' if ret=='void' else f'return ({ret})call_result.'+('p' if '*' in ret else 'i')+';')+'}')
 m=re.fullmatch(r'gl(Vertex|Color|Normal|TexCoord|RasterPos|Rect|MultiTexCoord)([1234]?)(ub|us|ui|b|s|i|f|d)(v?)(ARB)?',name)
 if not m:continue
 base,n,t,vector,arb=m.groups();n=(2 if vector else 4) if base=='Rect' else int(n or 3);offset=1 if base=='MultiTexCoord' else 0;typ=types[t]
 values=[]
 for k in range(n):
  v=f'((const {typ} *)a[{offset}].p)[{k}]' if vector else f'a[{offset+k}].'+('f' if t in ('f','d') else 'i')
  if base in ('Color','Normal') and t in scales:v=f'compat_clamp((float)({v})/{scales[t]},-1,1)'
  values.append(f'(float)({v})')
 check=[]
 if vector:check.append(f'!a[{offset}].p')
 if base=='Rect' and vector:check.append('!a[1].p')
 validation.append('case ID_'+name+':'+('if('+ '||'.join(check)+')return GL_INVALID_VALUE;' if check else '')+('if(a[0].i<GL_TEXTURE0_ARB||a[0].i>GL_TEXTURE0_ARB+1)return GL_INVALID_ENUM;' if base=='MultiTexCoord' else '')+'return 0;')
 if vector:
  family.append(f'case ID_{name}:if(!a[{offset}].p){{gl_error(c,GL_INVALID_VALUE);break;}}')
  # vector_size encodes pointer arg separately for multi coords (handled by recorder).
  vectors.append(f'case ID_{name}:return {n}*sizeof({typ});')
 else:family.append(f'case ID_{name}:')
 if base in ('Vertex','Color','TexCoord','MultiTexCoord','RasterPos'):
  values += ['0' if len(values)<2 else '0']*(max(0,3-len(values)))
  if len(values)==3:values+=['1']
 if base=='Vertex':family.append('glVertex4f('+','.join(values)+');break;')
 elif base=='Color':family.append('glColor4f('+','.join(values)+');break;')
 elif base=='Normal':family.append('glNormal3f('+','.join(values)+');break;')
 elif base in ('TexCoord','MultiTexCoord'):
  family.append('{' + ('int unit=(int)a[0].i-GL_TEXTURE0_ARB;if(unit<0||unit>1){gl_error(c,GL_INVALID_ENUM);break;}' if base=='MultiTexCoord' else 'int unit=0;')+'float v[4]={'+','.join(values)+'};for(int k=0;k<4;k++)c->texcoord[unit][k]=v[k];if(!unit)glTexCoord4f(v[0],v[1],v[2],v[3]);else for(int k=0;k<4;k++)c->tiny.current_tex_coord1.v[k]=v[k];}break;')
 elif base=='RasterPos':family.append('{V4 in={{'+','.join(values)+'}},eye,clip;gl_M4_MulV4(&eye,c->tiny.matrix_stack_ptr[0],&in);gl_M4_MulV4(&clip,c->tiny.matrix_stack_ptr[1],&eye);c->raster_valid=gl_user_visible(c,&eye)&&clip.v[3]>0&&clip.v[0]>=-clip.v[3]&&clip.v[0]<=clip.v[3]&&clip.v[1]>=-clip.v[3]&&clip.v[1]<=clip.v[3]&&clip.v[2]>=-clip.v[3]&&clip.v[2]<=clip.v[3];if(c->raster_valid){for(int k=0;k<4;k++)c->raster_color[k]=c->tiny.current_color.v[k];c->raster[0]=c->viewport[0]+(clip.v[0]/clip.v[3]+1)*c->viewport[2]/2;c->raster[1]=c->viewport[1]+(clip.v[1]/clip.v[3]+1)*c->viewport[3]/2;c->raster[2]=(c->range[0]+(clip.v[2]/clip.v[3]+1)*0.5f*(c->range[1]-c->range[0]))*(c->depth_bits==24?16777215:65535);}}break;')
 elif base=='Rect':
  if vector:
   # Rectv has two pointers, unlike ordinary vectors.
   family.append(f'{{const {typ} *x=a[0].p,*y=a[1].p;if(!x||!y){{gl_error(c,GL_INVALID_VALUE);break;}}glBegin(GL_QUADS);glVertex2f(x[0],x[1]);glVertex2f(y[0],x[1]);glVertex2f(y[0],y[1]);glVertex2f(x[0],y[1]);glEnd();}}break;')
  else:family.append('{float x='+values[0]+',y='+values[1]+',u='+values[2]+',v='+values[3]+';glBegin(GL_QUADS);glVertex2f(x,y);glVertex2f(u,y);glVertex2f(u,v);glVertex2f(x,v);glEnd();}break;')
code.append('void *gl_extension(const char *name){')
for row in rows[336:]:code.append('if(!w32_strcmp(name,"'+row['name']+'"))return (void *)w32_'+row['name']+';')
code.append('return 0;}')
(HERE/'api.c').write_text('\n'.join(code)+'\n')
(HERE/'ids.h').write_text('/* Generated by generate.py. */\nenum {\n'+'\n'.join(ids)+'\n GL_FUNCTION_COUNT };\n')
(HERE/'families.inc').write_text('/* Generated by generate.py. */\n'+'\n'.join(family)+'\n')
(HERE/'family_validation.inc').write_text('/* Generated numeric overload validation. */\n'+'\n'.join(validation)+'\n')
(HERE/'vectors.inc').write_text('/* Generated by generate.py. */\n'+'\n'.join(vectors)+'\n')

(HERE/"begin.inc").write_text("/* Generated legal Begin/End command names. */\n"+"\n".join("case ID_"+r["name"]+":legal=1;break;" for r in rows if re.match(r"gl(?:Vertex[234]|Color[34]|Normal3|TexCoord[1234]|MultiTexCoord[1234]|Material|EvalCoord|EdgeFlagv?$)",r["name"]) or r["name"] in ("glEnd","glArrayElement","glCallList","glCallLists"))+"\n")

for filename,prefix,guard in [('gl_client.h','','W32_GL_CLIENT_H'),('opengl32.h','w32_','W32_OPENGL32_H')]:
 path=HERE.parent/'include/w32'/filename
 path.write_text('/* Public GL 1.1 ABI shapes; generated by opengl32/generate.py. */\n#ifndef '+guard+'\n#define '+guard+'\n#include <w32/pixelformat.h>\n#include <w32/gl_types.h>\n'+'\n'.join(r['return']+' W32API '+prefix+r['name']+'('+r['args']+');' for r in rows)+'\n#include <w32/wgl.h>\n#endif\n')
(HERE.parents[2]/'tests/host/win32/gl/extensions.inc').write_text('/* Every declared extension function. Generated by generate.py. */\n'+'\n'.join('"'+r['name']+'",' for r in rows[336:])+'\n')
(HERE.parents[2]/'tests/host/win32/gl/aliases.h').write_text('/* Win32 ABI calls in the host model. Generated by generate.py. */\n'+'\n'.join('#define '+r['name']+' w32_'+r['name'] for r in rows)+'\n')

(HERE.parent/'include/w32/gl_extensions.h').write_text((HERE.parents[1]/'libgl/software/extensions.h').read_text())

# f7-14: the same engine for native programs. Native programs call plain cdecl
# gl* entry points; TinyGL's own public functions are renamed inside the native
# library so the engine remains the only owner of the public names.
NATIVE=HERE.parents[1]/'libgl'
types=(HERE.parent/'include/w32/gl_types.h').read_text().splitlines()
start=next(i for i,l in enumerate(types) if l.startswith('enum {'));end=max(i for i,l in enumerate(types) if l.strip()=='#endif')
extensions=(HERE.parents[1]/'libgl/software/extensions.h').read_text().splitlines()
extensions=[l for l in extensions if not l.startswith(('#ifndef CIUKI_GL_EXTENSIONS_H','#define CIUKI_GL_EXTENSIONS_H')) and not l.startswith('/*')]
extensions=extensions[:max(i for i,l in enumerate(extensions) if l.strip()=='#endif')]
header=['/* CiukiOS native OpenGL 1.1 subset: the shared GL engine with the scalar',
 ' * software backend and the render3d hardware path. Generated by',
 ' * sdk/win32/opengl32/generate.py from abi.json and extensions.json; the',
 ' * constants come from the retained TinyGL public header',
 ' * (sdk/libgl/LICENSE-TinyGL.txt). SPDX-License-Identifier: MIT */',
 '#ifndef CIUKI_GL_GL_H','#define CIUKI_GL_GL_H','#define GL_VERSION_1_1 1','#ifdef __cplusplus','extern "C" {','#endif',
 *extensions,*types[start:end],'',
 '/* Every entry point below is implemented by the engine (abi.json and',
 ' * extensions.json); header constants alone do not establish support. */']
header+=[r['return']+' '+r['name']+'('+r['args']+');' for r in rows]
header+=['#ifdef __cplusplus','}','#endif','#endif']
(NATIVE/'include/GL').mkdir(parents=True,exist_ok=True)
(NATIVE/'include/GL/gl.h').write_text('\n'.join(header)+'\n')
native=['/* Generated by sdk/win32/opengl32/generate.py; cdecl forwarding only. */','#include <GL/gl.h>','#include "dispatch.h"']
for row in rows:
 name,ret,args=(row[k] for k in ('name','return','args'))
 params=[]
 if args.strip() and args!='void':
  for arg in args.split(','):
   arg=arg.strip();param=re.search(r'(\w+)$',arg)[1];field='p' if '*' in arg else 'f' if any(t in arg for t in ('GLfloat','GLdouble')) else 'i';params.append('{.'+field+'='+param+'}')
 native.append(f'{ret} {name}({args}){{union gl_arg call_args[12]={{'+(','.join(params) if params else '{.i=0}')+'};union gl_arg call_result=w32_gl_dispatch(ID_'+name+',call_args);'+('(void)call_result;' if ret=='void' else f'return ({ret})call_result.'+('p' if '*' in ret else 'i')+';')+'}')
# The engine's array/list replay names the Win32 entry points; natively they
# are the same public cdecl functions.
for row in rows:
 if row['name'] in ('glBegin','glEnd','glVertex4f','glColor4f','glNormal3f'):
  args=row['args'];params='' if args=='void' else ','.join(re.search(r'(\w+)$',a.strip())[1] for a in args.split(','))
  native.append(f"void w32_{row['name']}({args}){{{row['name']}({params});}}")
native.append('void *gl_extension(const char *name){')
for row in rows[336:]:native.append('if(!ciuki_gl_strcmp(name,"'+row['name']+'"))return (void *)'+row['name']+';')
native.append('return 0;}')
(NATIVE/'native/api.c').write_text('\n'.join(native)+'\n')
# TinyGL public names: every declaration of the retained header (including the
# PROTO_GL families) plus every gl[A-Z]* definition in the vendor sources.
import subprocess
preprocessed=subprocess.check_output(['clang','-E','-P','-I'+str(NATIVE/'vendor/include'),str(NATIVE/'vendor/include/GL/gl.h')],text=True)
names=set(re.findall(r'\b(gl[A-Z]\w*)\s*\(',preprocessed))
for source in sorted((NATIVE/'vendor/src').glob('*.c')):
 names|=set(re.findall(r'^[A-Za-z_][\w \*]*?\b(gl[A-Z]\w*)\s*\(',source.read_text(),re.M))
(NATIVE/'native/tinygl_rename.h').write_text('/* Generated by sdk/win32/opengl32/generate.py: TinyGL public names are\n * private to the native library; the engine owns the public gl* names. */\n'+'\n'.join('#define '+n+' tgl_'+n for n in sorted(names))+'\n')
