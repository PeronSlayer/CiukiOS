#ifndef CIUKI_SDK_REGISTRY_H
#define CIUKI_SDK_REGISTRY_H
#include <stddef.h>
#include <stdint.h>
#define REG_DIRECTORY "/System/Registry"
#define REG_NAME_CHARS 64u
#define REG_NAME_BYTES 256u
#define REG_DEPTH_MAX 16u
#define REG_PATH_MAX (REG_DEPTH_MAX * (REG_NAME_BYTES + 1u))
#define REG_TEXT_MAX (256u * 1024u)
#define REG_KEYS_MAX 1024u
#define REG_VALUES_MAX 4096u
#define REG_DATA_MAX 4096u
#define REG_GENERATION_ERROR UINT64_MAX
struct reg_root;
enum reg_type { REG_STRING = 1, REG_INT32, REG_BOOL, REG_BINARY };
struct reg_value_info { char name[REG_NAME_BYTES + 1]; enum reg_type type; size_t size; };
/* libreg.a: synchronous UTF-8 text registry. Roots System/Desktop/Programs/Users
 * are persistent; Hardware is generated by ciuki_devices and read-only.
 * Paths include the root, e.g. System\\Version. Names compare with pinned
 * Unicode 16 full case folding, without normalization. Returns 0 / -1 errno,
 * except open (NULL on error) and generation (UINT64_MAX on error).
 * One writer per root at a time, including regedit and the owning app; caller
 * serializes same-handle calls. Mutations refresh stale handles and check the
 * disk generation before commit (EAGAIN on a race). No interprocess lock/CAS.
 * See docs/design/registry-contract.md for text grammar and recovery limits. */
struct reg_root *reg_open_root(const char *name);
struct reg_root *reg_open_root_at(const char *name, const char *directory);
void reg_close_root(struct reg_root *);
const char *reg_root_name(const struct reg_root *);
int reg_read_only(const struct reg_root *);
int reg_name_equal(const char *, const char *);
uint64_t reg_generation(struct reg_root *);
int reg_create_key(struct reg_root *, const char *key);
/* name == NULL recursively deletes a branch; deleting a root is forbidden. */
int reg_delete(struct reg_root *, const char *key, const char *name);
int reg_get_int32(struct reg_root *, const char *key, const char *name, int32_t *);
int reg_get_bool(struct reg_root *, const char *key, const char *name, int *);
/* *size is caller capacity, then required bytes (string includes NUL). NULL
 * output queries size. ERANGE leaves output unchanged and supplies size. */
int reg_get_string(struct reg_root *, const char *key, const char *name, char *, size_t *size);
int reg_get_binary(struct reg_root *, const char *key, const char *name, void *, size_t *size);
int reg_set_string(struct reg_root *, const char *key, const char *name, const char *);
int reg_set_int32(struct reg_root *, const char *key, const char *name, int32_t);
int reg_set_bool(struct reg_root *, const char *key, const char *name, int);
int reg_set_binary(struct reg_root *, const char *key, const char *name, const void *, size_t);
/* Immediate children, in preserved insertion order. ENOENT ends enumeration.
 * All returned names/info are caller-owned copies; reads refresh the root. */
int reg_enum_keys(struct reg_root *, const char *key, unsigned index, char *, size_t);
int reg_enum_values(struct reg_root *, const char *key, unsigned index, struct reg_value_info *);
/* Typed literal helpers for text editors (quoted string, int32, bool, hex:).
 * get uses the same capacity/size-query convention as get_string. */
int reg_get_text(struct reg_root *, const char *key, const char *name, char *, size_t *);
int reg_set_text(struct reg_root *, const char *key, const char *name, const char *literal);
/* Absolute file paths. Export a branch; import merges a fully validated file
 * containing only this root. Export cannot overwrite the registry's own files.
 * Import is one root transaction; no deletion or cross-root transaction syntax. */
int reg_export(struct reg_root *, const char *key, const char *path);
int reg_import(struct reg_root *, const char *path);
#endif
