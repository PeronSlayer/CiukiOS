#!/usr/bin/env python3
"""Prepare/check deterministic Tango sprites for the desktop and libdeskui.

Each sprite is an original 16x16, 22x22 or 32x32 PNG from the pinned archive,
converted to AARRGGBB words without resizing.

Pillow is needed only for preparation; normal builds verify pinned bytes using
the standard library. Ciuki artwork is not included or converted by this tool.
"""
# SPDX-License-Identifier: MIT
import hashlib
import io
import json
from pathlib import Path
import sys
import tarfile

ROOT = Path(__file__).resolve().parents[2]
ARCHIVE = ROOT / "assets/icons/upstream/tango-icon-theme-0.8.90.tar.gz"
ARCHIVE_SHA = "6e98d8032d57d818acc907ec47e6a718851ff251ae7c29aafb868743eb65c88e"
HERE = Path(__file__).resolve().parent
MEMBERS = {"run": "mimetypes/application-x-executable", "restart": "actions/system-shutdown",
           "back": "actions/go-previous", "forward": "actions/go-next", "up": "actions/go-up",
           "cut": "actions/edit-cut", "copy": "actions/edit-copy", "paste": "actions/edit-paste",
           "delete": "actions/edit-delete", "properties": "actions/document-properties",
           "views": "actions/view-fullscreen", "folder": "places/folder",
           "text": "mimetypes/text-x-generic", "refresh": "actions/view-refresh",
           # f2-31: Files and libdeskui (menu entry, places, file types, dialogs).
           "files": "apps/system-file-manager", "folder_open": "status/folder-open",
           "harddisk": "devices/drive-harddisk", "generic": "mimetypes/text-x-generic-template",
           "image": "mimetypes/image-x-generic", "audio": "mimetypes/audio-x-generic",
           "script": "mimetypes/text-x-script",
           "back22": "actions/go-previous", "forward22": "actions/go-next", "up22": "actions/go-up",
           "cut22": "actions/edit-cut", "copy22": "actions/edit-copy", "paste22": "actions/edit-paste",
           "delete22": "actions/edit-delete", "properties22": "actions/document-properties",
           "views22": "actions/format-justify-fill",
           "folder32": "places/folder", "text32": "mimetypes/text-x-generic",
           "run32": "mimetypes/application-x-executable", "generic32": "mimetypes/text-x-generic-template",
           "image32": "mimetypes/image-x-generic", "audio32": "mimetypes/audio-x-generic",
           "script32": "mimetypes/text-x-script", "harddisk32": "devices/drive-harddisk",
           "files32": "apps/system-file-manager", "dialog_info32": "status/dialog-information",
           "dialog_warning32": "status/dialog-warning", "dialog_error32": "status/dialog-error",
           "dialog_question32": "apps/help-browser"}


def size_of(name):
    return 22 if name.endswith("22") else 32 if name.endswith("32") else 16


def source_of(name, member):
    size = size_of(name)
    return f"tango-icon-theme-0.8.90/{size}x{size}/{member}.png"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def check():
    record = json.loads((HERE / "shell-icons.json").read_text())
    if sha(ARCHIVE.read_bytes()) != ARCHIVE_SHA or record["archive_sha256"] != ARCHIVE_SHA:
        raise ValueError("Tango archive changed")
    if sha((HERE / "shell_icons.h").read_bytes()) != record["header_sha256"]:
        raise ValueError("stale Tango shell icons")
    with tarfile.open(ARCHIVE) as archive:
        for name, member in MEMBERS.items():
            source = source_of(name, member)
            if record["icons"][name]["source"] != source or sha(archive.extractfile(source).read()) != record["icons"][name]["source_sha256"]:
                raise ValueError("Tango source provenance")
    return record


def prepare():
    from PIL import Image
    if sha(ARCHIVE.read_bytes()) != ARCHIVE_SHA:
        raise ValueError("Tango archive changed")
    lines = ["/* Deterministic Tango 0.8.90 RGBA sprites; Public Domain.",
             " * Upstream authors/notices: assets/icons/upstream/{AUTHORS,COPYING}.",
             " * Generated by apps/desktop/convert_icons.py. */",
             "#ifndef CIUKI_SHELL_ICONS_H", "#define CIUKI_SHELL_ICONS_H"]
    record = {"archive_sha256": ARCHIVE_SHA, "license": "Tango 0.8.90 Public Domain",
              "conversion": "original 16x16, 22x22 or 32x32 PNG RGBA8, no resizing; AARRGGBB", "icons": {}}
    with tarfile.open(ARCHIVE) as archive:
        for name, member in MEMBERS.items():
            source = source_of(name, member)
            size = size_of(name)
            data = archive.extractfile(source).read()
            im = Image.open(io.BytesIO(data)).convert("RGBA")
            if im.size != (size, size):
                raise ValueError("Tango sprite size")
            raw = im.tobytes()
            values = [(raw[k+3] << 24) | (raw[k] << 16) | (raw[k+1] << 8) | raw[k+2]
                      for k in range(0, len(raw), 4)]
            lines.append(f"static const uint32_t desk_icon_{name}[{size * size}] = {{")
            for k in range(0, size * size, 8):
                lines.append("    " + ",".join(f"0x{v:08x}u" for v in values[k:k+8]) + ",")
            lines.append("};")
            record["icons"][name] = {"source": source, "source_sha256": sha(data), "rgba_sha256": sha(raw)}
    lines.append("#endif")
    header = ("\n".join(lines)+"\n").encode()
    (HERE / "shell_icons.h").write_bytes(header)
    record["header_sha256"] = sha(header)
    (HERE / "shell-icons.json").write_text(json.dumps(record, indent=2, sort_keys=True)+"\n")


if __name__ == "__main__":
    if sys.argv[1:] == ["--prepare"]:
        prepare()
    elif sys.argv[1:] != ["--check"]:
        raise SystemExit("usage: convert_icons.py --check|--prepare")
    check()
