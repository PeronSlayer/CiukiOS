/* SPDX-License-Identifier: MIT
 * CiukiOS look: themes, settings file, anti-aliased fonts and integer paint
 * helpers shared by the compositor (window frames, shell) and libdeskui
 * (controls). Everything is integer-only; equal inputs give equal pixels.
 *
 * Themes are compiled in and selected at run time by name. The shell owns
 * DESK_SETTINGS_PATH (settings.h, key=value lines); the desktop and every
 * libdeskui client read its "theme" key at start and follow later changes
 * through desk_theme_poll(). The Control Panel writes the key with
 * cfg_format (persisted), applies it to itself with du_theme_use and asks
 * the desktop to reload (DESK_SETTINGS), which applies it at once. */
#ifndef CIUKI_DESK_THEME_H
#define CIUKI_DESK_THEME_H
#include <stdint.h>
#include <stddef.h>

/* ---- fonts (data: ui_fonts.h, generated by convert_fonts.py) ---- */
struct desk_glyph { uint32_t offset; uint8_t w, h; int8_t left, top; uint8_t advance; };
struct desk_font { const char *name; int size, ascent, descent; const struct desk_glyph *glyphs; const uint8_t *alpha; };
enum { DESK_FONT_UI, DESK_FONT_BOLD, DESK_FONT_TITLE, DESK_FONT_MONO, DESK_FONT_MONO_BOLD, DESK_FONT_LARGE, DESK_FONTS };
const struct desk_font *desk_font(int id);
int desk_font_cap(int id);                                   /* capital height in pixels */
int desk_font_line(int id);                                  /* ascent + descent */
int desk_text_advance(int font, unsigned codepoint);
int desk_text_measure(int font, const char *utf8);           /* pixels; '&' is literal */
int desk_text_measure_n(int font, const char *utf8, size_t chars);
size_t desk_text_fit_chars(int font, const char *utf8, int width); /* characters that fit */
unsigned desk_utf8_decode(const char *s, size_t *used);

/* ---- paint target: XRGB8888 pixels and a clip rectangle ---- */
struct desk_paint { uint32_t *pixels; int width, height, cx, cy, cw, ch; };
uint32_t desk_mix(uint32_t a, uint32_t b, unsigned alpha);   /* alpha 0..255 of a over b */
void desk_paint_fill(struct desk_paint *, int x, int y, int w, int h, uint32_t);
void desk_paint_blend(struct desk_paint *, int x, int y, int w, int h, uint32_t, unsigned alpha);
void desk_paint_vgradient(struct desk_paint *, int x, int y, int w, int h, uint32_t top, uint32_t bottom);
void desk_paint_hgradient(struct desk_paint *, int x, int y, int w, int h, uint32_t left, uint32_t right);
void desk_paint_shadow(struct desk_paint *, int x, int y, int w, int h, int size, uint32_t colour);
/* Draws at the pen (x, baseline); returns the advance. */
int desk_paint_text(struct desk_paint *, int font, int x, int baseline, const char *utf8, uint32_t colour);
int desk_paint_text_n(struct desk_paint *, int font, int x, int baseline, const char *utf8, size_t chars, uint32_t colour);
/* Title-bar and control ornaments drawn in the current theme. */
void desk_paint_pinstripes(struct desk_paint *, int x, int y, int w, int h, uint32_t light, uint32_t dark);
void desk_paint_raised(struct desk_paint *, int x, int y, int w, int h, int pressed, int hot);
/* Rounded rectangle (radius r, anti-aliased corners): vertical gradient face
 * and a 1 px outline; outline 0 alpha draws none (alpha 0..255). */
void desk_paint_round_rect(struct desk_paint *, int x, int y, int w, int h, int r,
                           uint32_t top, uint32_t bottom, uint32_t outline, unsigned outline_alpha);
/* A 16x16 (or size x size) ARGB icon, alpha in the top byte, blended at (x, y). */
void desk_paint_icon(struct desk_paint *, int x, int y, const uint32_t *argb, int size);
enum { DESK_GLYPH_CLOSE, DESK_GLYPH_MINIMIZE, DESK_GLYPH_ZOOM, DESK_GLYPH_COLLAPSE, DESK_GLYPH_EXPAND };
/* One title-bar button in the current theme at its hit box (x, y, w, h):
 * the theme's square (or Classic caption button) centred in that box. */
void desk_paint_title_button(struct desk_paint *, int x, int y, int w, int h, int kind, int active, int hot, int pressed);

/* ---- window frames ----
 * One painter for every frame: desktop windows (applications, the built-in
 * About, Run, Shut Down and message windows, the DOS window) and libdeskui's
 * modal dialogs. Frame geometry and title-button hit boxes are the same in
 * every theme; only colours and ornaments change. */
#define DESK_FRAME_BORDER 3
#define DESK_FRAME_TITLE 24
#define DESK_FRAME_BUTTON 18                          /* square hit box of a title button */
enum { DESK_TB_CLOSE = 1, DESK_TB_MINIMIZE = 2, DESK_TB_COLLAPSE = 4 };
struct desk_frame_style {
    const char *title;
    const uint32_t *icon;         /* 16x16 ARGB window icon (gradient captions), or NULL */
    int active, alert, collapsed; /* alert: not responding */
    unsigned buttons;             /* DESK_TB_* drawn (each only when the frame is wide enough) */
    unsigned hot, pressed;        /* the DESK_TB_* button under the pointer / held down, or 0 */
};
/* Hit box (x, y, w, h) of title button `button` (DESK_TB_*) of a frame at
 * (x, y) of width w; w and h are 0 when the frame is too narrow for it. */
void desk_title_button_box(int x, int y, int w, unsigned button, int box[4]);
/* Paints the whole frame: face, title bar, buttons, content well and the
 * 1 px outline with the theme's corners. The caller draws the content at
 * (x + DESK_FRAME_BORDER, y + DESK_FRAME_TITLE) and the drop shadow. */
void desk_paint_frame(struct desk_paint *, int x, int y, int w, int h, const struct desk_frame_style *);

/* ---- themes ---- */
enum { DESK_TITLE_FLAT, DESK_TITLE_GRADIENT, DESK_TITLE_PINSTRIPE };
enum { DESK_CONTROLS_CLASSIC, DESK_CONTROLS_PLATINUM };
enum { DESK_FOCUS_DOTTED, DESK_FOCUS_RING };

struct desk_theme {
    const char *name, *description;
    /* desktop and shell */
    uint32_t desktop, desktop_label;
    uint32_t topbar, topbar_edge, topbar_text, topbar_accent;
    uint32_t taskbar, taskbar_text, start, start_open, start_text, task_active, task_active_text;
    /* 3-D face, bevels and content */
    uint32_t face, light, hilite, shadow, dark, outline;
    uint32_t face_top, face_bottom, hover;
    uint32_t window, ink, gray, select, select_ink, accent, focus;
    /* window frame */
    uint32_t frame, frame_inactive;
    uint32_t title[2], title_inactive[2], title_text, title_text_inactive;
    uint32_t stripe_light, stripe_dark, drop_shadow;
    /* styles and metrics */
    uint8_t title_style, title_center, control_style, focus_style, text_aa;
    uint8_t radius, shadow_size, button;              /* frame corner radius, shadow size, title button size */
    uint8_t icon_small, icon_toolbar, icon_large; /* 16, 22, 32: slots for du_icon(name, size) */
    uint8_t font_ui, font_bold, font_title, font_mono, font_mono_bold, font_large;
};
extern const struct desk_theme *desk_theme;                  /* current, never NULL */
int desk_theme_count(void);
const struct desk_theme *desk_theme_at(int index);
const struct desk_theme *desk_theme_named(const char *name); /* ASCII case-insensitive */
int desk_theme_use(const char *name);                         /* 0, or -1 (unchanged) */

/* ---- settings file (owned by the shell) ----
 * One file, one format: settings.c (cfg_parse/cfg_format, CFG_FILE) writes
 * it; the theme engine reads its "theme" key with the same line rules. */
#define DESK_SETTINGS_DIR "/system/settings"
#define DESK_SETTINGS_PATH "/system/settings/desktop.cfg"
/* The last valid "theme=" line of a desktop.cfg text, as the theme's
 * canonical name; 0, or -1 when there is none. */
int desk_settings_theme(const char *text, size_t length, char *name, size_t size);
/* Reads the theme key from `path` at most once per two seconds of `now_ns`
 * (and at once on the first call); returns 1 when the current theme changed. */
int desk_theme_poll(const char *path, uint64_t now_ns);
#endif
