#!/usr/bin/env python3
"""Prepare/check the desktop's anti-aliased UI fonts (ui_fonts.h).

The 0.8 line rasterized the OFL fonts in assets/fonts/upstream to 1-bit
.CFN files (legacy-0.8:scripts/build_fonts.py). This converter keeps that
pipeline's sources, licences and variable-axis handling and emits 8-bit
coverage maps instead, cropped to each glyph's ink box, for the integer-only
compositor and libdeskui (apps/desktop/theme.c draws them).

  convert_fonts.py --prepare   rasterize (Pillow with FreeType) and pin
  convert_fonts.py --check     verify sources and header (standard library)

Character set: U+0020-U+007E, U+00A0-U+00FF, U+2022 and U+2026. Advances
are FreeType's hinted advances rounded to whole pixels; no kerning. The
conversions are Modified Versions under each font's licence (SIL OFL 1.1,
no Reserved Font Name): assets/fonts/LICENSES.TXT and the OFL.txt files.
"""
# SPDX-License-Identifier: MIT
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
UP = ROOT / "assets/fonts/upstream"
CODES = [*range(0x20, 0x7f), *range(0xa0, 0x100), 0x2022, 0x2026]
# (id, C name, source, licence file, pixel size, weight)
FACES = [
    ("DESK_FONT_UI", "Inter 12", "inter/Inter[opsz,wght].ttf", "inter/OFL.txt", 12, 400),
    ("DESK_FONT_BOLD", "Inter 12 SemiBold", "inter/Inter[opsz,wght].ttf", "inter/OFL.txt", 12, 600),
    ("DESK_FONT_TITLE", "Inter 13 Bold", "inter/Inter[opsz,wght].ttf", "inter/OFL.txt", 13, 700),
    ("DESK_FONT_MONO", "Inconsolata 12", "inconsolata/Inconsolata[wdth,wght].ttf", "inconsolata/OFL.txt", 12, 400),
    ("DESK_FONT_MONO_BOLD", "Inconsolata 12 Bold", "inconsolata/Inconsolata[wdth,wght].ttf", "inconsolata/OFL.txt", 12, 700),
    ("DESK_FONT_LARGE", "Inter 22 Bold", "inter/Inter[opsz,wght].ttf", "inter/OFL.txt", 22, 700),
    # Desktop icon labels (shell.c draw_icons): white with a soft dark halo on the wallpaper.
    ("DESK_FONT_LABEL", "Inter 13", "inter/Inter[opsz,wght].ttf", "inter/OFL.txt", 13, 400),
]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def load(path, size, weight):
    from PIL import ImageFont
    font = ImageFont.truetype(str(path), size)
    axes = font.get_variation_axes()
    values = []
    for axis in axes:
        name = axis["name"] if isinstance(axis["name"], str) else axis["name"].decode()
        tag = name.lower()
        if tag.startswith("weight"):
            values.append(weight)
        elif tag.startswith("width"):
            values.append(100)
        elif tag.startswith("optical"):
            values.append(max(axis["minimum"], min(axis["maximum"], size)))
        else:
            values.append(axis["default"])
    font.set_variation_by_axes(values)
    return font


def rasterize(font):
    """Per glyph: advance, ink box offset from the pen/baseline, coverage."""
    from PIL import Image, ImageDraw
    ascent, descent = font.getmetrics()
    glyphs, alpha = [], bytearray()
    for code in CODES:
        ch = chr(code)
        advance = max(1, round(font.getlength(ch)))
        pad = 8
        size = (font.size * 3 + 2 * pad, ascent + descent + 2 * pad)
        im = Image.new("L", size)
        ImageDraw.Draw(im).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        box = im.getbbox()
        if not box:
            glyphs.append((len(alpha), 0, 0, 0, 0, advance))
            continue
        x0, y0, x1, y1 = box
        crop = im.crop(box).tobytes()
        glyphs.append((len(alpha), x1 - x0, y1 - y0, x0 - pad, y0 - pad - ascent, advance))
        alpha += crop
    return ascent, descent, glyphs, bytes(alpha)


def prepare():
    import PIL
    from PIL import features
    lines = ["/* Anti-aliased UI fonts for the CiukiOS desktop and libdeskui.",
             " * Generated by apps/desktop/convert_fonts.py from assets/fonts/upstream;",
             " * SIL Open Font License 1.1 (assets/fonts/LICENSES.TXT, upstream OFL.txt).",
             " * Glyph: alpha offset, width, height, left and top (from the pen on the",
             " * baseline), advance. Do not edit. */",
             "#ifndef CIUKI_UI_FONTS_H", "#define CIUKI_UI_FONTS_H",
             f"#define DESK_FONT_CODES {len(CODES)}"]
    record = {"conversion": "Pillow ImageFont (FreeType hinting, 8-bit coverage), ink-box crop, rounded advances",
              "pillow": PIL.__version__, "freetype": features.version("freetype2"),
              "codes": "U+0020-007E, U+00A0-00FF, U+2022, U+2026", "faces": {}}
    for ident, name, source, licence, size, weight in FACES:
        path = UP / source
        ascent, descent, glyphs, alpha = rasterize(load(path, size, weight))
        c = ident.lower()
        lines.append(f"static const uint8_t {c}_alpha[{max(1, len(alpha))}] = {{")
        for k in range(0, len(alpha), 24):
            lines.append("    " + ",".join(str(v) for v in alpha[k:k+24]) + ",")
        if not alpha:
            lines.append("    0,")
        lines.append("};")
        lines.append(f"static const struct desk_glyph {c}_glyphs[DESK_FONT_CODES] = {{")
        for k in range(0, len(glyphs), 6):
            lines.append("    " + "".join("{%d,%d,%d,%d,%d,%d}," % g for g in glyphs[k:k+6]))
        lines.append("};")
        record["faces"][ident] = {"name": name, "source": f"upstream/{source}", "source_sha256": sha(path.read_bytes()),
                                  "licence": "OFL-1.1", "licence_file": f"upstream/{licence}", "size": size,
                                  "weight": weight, "ascent": ascent, "descent": descent,
                                  "alpha_sha256": sha(alpha)}
    lines.append("static const struct desk_font desk_fonts[DESK_FONTS] = {")
    for ident, name, source, licence, size, weight in FACES:
        f = record["faces"][ident]
        c = ident.lower()
        lines.append(f'    [{ident}] = {{"{name}", {size}, {f["ascent"]}, {f["descent"]}, {c}_glyphs, {c}_alpha}},')
    lines.append("};")
    lines.append("#endif")
    header = ("\n".join(lines) + "\n").encode()
    (HERE / "ui_fonts.h").write_bytes(header)
    record["header_sha256"] = sha(header)
    (HERE / "ui-fonts.json").write_text(json.dumps(record, indent=2, sort_keys=True) + "\n")


def check():
    record = json.loads((HERE / "ui-fonts.json").read_text())
    if sha((HERE / "ui_fonts.h").read_bytes()) != record["header_sha256"]:
        raise ValueError("stale UI fonts header; run convert_fonts.py --prepare")
    names = [f[0] for f in FACES]
    if sorted(record["faces"]) != sorted(names):
        raise ValueError("UI font face list changed")
    for ident, name, source, licence, size, weight in FACES:
        face = record["faces"][ident]
        if (face["source"] != f"upstream/{source}" or face["size"] != size or face["weight"] != weight or
                sha((UP / source).read_bytes()) != face["source_sha256"] or not (UP / licence).is_file()):
            raise ValueError(f"UI font source provenance: {ident}")
    return record


if __name__ == "__main__":
    if sys.argv[1:] == ["--prepare"]:
        prepare()
    elif sys.argv[1:] != ["--check"]:
        raise SystemExit("usage: convert_fonts.py --check|--prepare")
    print(f"[fonts] {len(check()['faces'])} UI faces match their pinned sources")
