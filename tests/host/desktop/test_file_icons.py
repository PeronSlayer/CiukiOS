"""fx-exeicons: programs, shortcuts, PIFs, folders and media show their own icons.

Host tests of the bounded extraction core (apps/libdeskui/iconx.c) and the
libdeskui file icon service (apps/libdeskui/fileicon.c) on synthetic
fixtures generated by icon_fixtures.py: ICO/CUR/ANI/BMP, PE32/PE32+ and NE
resource trees, MS-SHLLINK and CIUKLNK3 shortcuts, PIFs, desktop.ini and
AUTORUN.INF. Malformed and mutated files must fail cleanly within the read
budget (ASan/UBSan). The optional local check reads the mounted Half-Life
CD read-only and copies nothing. Scratch lives under build/host/file-icons.

    python3 -B -m unittest tests.host.desktop.test_file_icons -v
"""
