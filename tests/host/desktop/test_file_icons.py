def checker(r, g, b, r2=0, g2=0, b2=0, step=4, hole=None):
    def f(x, y):
        if hole and hole(x, y):
            return (0, 0, 0, 0)
        return (255, r, g, b) if ((x // step + y // step) & 1) else (255, r2, g2, b2)
    return f


def gradient(w, h, alpha=False):
    def f(x, y):
        a = (x * 255) // max(1, w - 1) if alpha else 255
        return (a, (x * 7) & 255, (y * 11) & 255, ((x + y) * 5) & 255)
    return f


def parse(line):
    out = {}
    for part in line.split():
        if '=' in part:
            k, v = part.split('=', 1)
            out[k] = v
    return out


class FileIconTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        shutil.rmtree(OUT, ignore_errors=True)
        OUT.mkdir(parents=True)
        cls.binary = tool.build(OUT)
        cls.env = tool.environment()

    def run_tool(self, *args, env=None):
        result = subprocess.run([str(self.binary), *map(str, args)], env={**self.env, **(env or {})},
                                capture_output=True, text=True, timeout=120)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertNotIn('runtime error', result.stderr)
        return result.stdout

    def write(self, name, data):
        path = OUT / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return path

    def extract(self, path, index, size, full=False):
        line = self.run_tool('extract', path, index, size, *(['full'] if full else []))
        r = parse(line)
        if 'pixels' in r:
            r['pixels'] = [int(v, 16) for v in r['pixels'].split(',')]
        r['status'] = int(r['status'])
        return r

    # ---- images and directories ------------------------------------------------
    def test_ico_exact_sizes_and_depth_choice(self):
        hole = lambda x, y: x < 2 and y < 3   # noqa: E731
        i16 = fx.Image(16, 16, checker(200, 10, 10, hole=hole), bpp=4)
        i32a = fx.Image(32, 32, checker(10, 200, 10, 0, 0, 255, hole=hole), bpp=8)
        i32b = fx.Image(32, 32, lambda x, y: (0, 0, 0, 0) if hole(x, y) else gradient(32, 32)(x, y), bpp=24)
        i48 = fx.Image(48, 48, gradient(48, 48, alpha=True), bpp=32, alpha=True)
        path = self.write('set.ico', fx.ico([i16, i32a, i32b, i48]))
        r = self.extract(path, 0, 16, True)
        self.assertEqual((r['status'], r['width'], r['depth']), (0, '16', '4'))
        self.assertEqual(r['pixels'], i16.expected())
        r = self.extract(path, 0, 32, True)
        self.assertEqual((r['width'], r['depth'], r['entry']), ('32', '24', '2'))   # deepest of the 32 px images
        self.assertEqual(r['pixels'], i32b.expected())
        r = self.extract(path, 0, 48, True)
        self.assertEqual((r['width'], r['depth']), ('48', '32'))
        self.assertEqual(r['pixels'], i48.expected())
        self.assertEqual(self.extract(path, 1, 32)['status'], -4)   # an .ico holds one icon

    def test_scaling_uses_the_area_filter(self):
        i48 = fx.Image(48, 48, gradient(48, 48), bpp=24)
        path = self.write('big.ico', fx.ico([i48]))
        for size in (16, 22, 32, 47):
            r = self.extract(path, 0, size, True)
            self.assertEqual(r['status'], 0)
            self.assertEqual(r['pixels'], fx.area(i48.expected(), 48, 48, size), size)
        i16 = fx.Image(16, 16, checker(1, 2, 3, 250, 240, 230, step=2), bpp=8)
        small = self.write('small.ico', fx.ico([i16]))
        r = self.extract(small, 0, 48, True)
        self.assertEqual(r['pixels'], fx.area(i16.expected(), 16, 16, 48))
        # A tie in size distance prefers the larger image (a downscale).
        tie = self.write('tie.ico', fx.ico([fx.Image(16, 16, checker(9, 9, 9), bpp=8), fx.Image(48, 48, checker(9, 9, 9), bpp=8)]))
        self.assertEqual(self.extract(tie, 0, 32)['width'], '48')

    def test_pixel_formats(self):
        cases = [fx.Image(32, 32, checker(255, 255, 255), bpp=1), fx.Image(32, 32, gradient(32, 32), bpp=16),
                 fx.Image(32, 32, checker(1, 2, 3, 4, 5, 6), bpp=4, core=True), fx.Image(20, 20, gradient(20, 20), bpp=24)]
        for n, image in enumerate(cases):
            path = self.write(f'format{n}.ico', fx.ico([image]))
            r = self.extract(path, 0, image.w, True)
            self.assertEqual(r['status'], 0, n)
            self.assertEqual(r['pixels'], image.expected(), n)

    def test_inverting_mask_pixels(self):
        # AND = 1 over white XOR (a cursor's inverted pixels) is shown as black.
        image = fx.Image(16, 16, lambda x, y: (255, 255, 255, 255), bpp=4, mask_override=lambda x, y: x < 4)
        path = self.write('invert.cur', fx.ico([image], cursor=True))
        r = self.extract(path, 0, 16, True)
        self.assertEqual(r['kind'], '2')
        row = r['pixels'][:16]
        self.assertEqual(row[:4], [0xff000000] * 4)
        self.assertEqual(row[4:], [0xffffffff] * 12)

    def test_png_and_damaged_images_yield_to_the_next(self):
        good = fx.Image(32, 32, checker(5, 50, 100), bpp=8)
        png = fx.Image(32, 32, checker(1, 1, 1), bpp=32, alpha=True)
        png_bytes = b'\x89PNG\r\n\x1a\n' + bytes(64)
        path = self.write('vista.ico', fx.ico([png, good], raw=[png_bytes, good.dib()]))
        r = self.extract(path, 0, 32, True)
        self.assertEqual((r['status'], r['entry']), (0, '1'))
        self.assertEqual(r['pixels'], good.expected())
        broken = self.write('broken.ico', fx.ico([png], raw=[png_bytes]))
        self.assertEqual(self.extract(broken, 0, 32)['status'], -2)

    def test_pe_group_order_and_resource_ids(self):
        def icon(c):
            return [fx.Image(16, 16, checker(*c), bpp=8), fx.Image(32, 32, checker(*c), bpp=8)]
        groups = [('ZETA', icon((1, 0, 0))), ('ALPHA', icon((2, 0, 0))), (5, icon((3, 0, 0))), (2, icon((4, 0, 0)))]
        for plus in (False, True):
            path = self.write(f'groups{int(plus)}.exe', fx.pe(groups, plus=plus))
            r = self.extract(path, 0, 32, True)
            self.assertEqual((r['status'], r['kind'], r['count']), (0, '5', '4'))
            self.assertEqual(r['pixels'], icon((2, 0, 0))[1].expected())    # named groups first, sorted
            self.assertEqual(r['group'], '0')
            r = self.extract(path, 1, 16, True)
            self.assertEqual(r['pixels'], icon((1, 0, 0))[0].expected())
            r = self.extract(path, 2, 32, True)
            self.assertEqual((r['group'], r['pixels']), ('2', icon((4, 0, 0))[1].expected()))
            r = self.extract(path, -5, 32, True)
            self.assertEqual((r['group'], r['pixels']), ('5', icon((3, 0, 0))[1].expected()))
            self.assertEqual(self.extract(path, 4, 32)['status'], -4)
            self.assertEqual(self.extract(path, -7, 32)['status'], -4)

    def test_ne_groups(self):
        a = [fx.Image(32, 32, checker(10, 20, 30), bpp=4)]
        b = [fx.Image(32, 32, checker(40, 50, 60), bpp=8), fx.Image(16, 16, checker(40, 50, 60), bpp=8)]
