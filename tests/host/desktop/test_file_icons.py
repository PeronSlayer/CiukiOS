    def test_hostile_tables_fail_within_the_budget(self):
        icon = [fx.Image(32, 32, checker(1, 2, 3), bpp=8)]
        data = bytearray(fx.pe([(1, icon)]))
        # A resource directory entry pointing back at its own directory.
        root = 0x200
        struct.pack_into('<I', data, root + 16 + 4, 0x80000000)
        loop = self.write('loop.exe', bytes(data))
        self.assertLess(self.extract(loop, 0, 32)['status'], 0)
        # A group claiming 65535 images; an ICO claiming images past the end.
        data = bytearray(fx.ico(icon))
        struct.pack_into('<H', data, 4, 65535)
        self.assertLess(self.extract(self.write('many.ico', bytes(data)), 0, 32)['status'], 0)
        data = bytearray(fx.ico(icon))
        struct.pack_into('<I', data, 6 + 12, 0x7fffff00)
        self.assertLess(self.extract(self.write('far.ico', bytes(data)), 0, 32)['status'], 0)
        # A DIB whose dimensions exceed the data, and one 4096 px wide.
        data = bytearray(fx.ico(icon))
        at = struct.unpack_from('<I', data, 6 + 12)[0]
        struct.pack_into('<i', data, at + 4, 4096)
        self.assertLess(self.extract(self.write('wide.ico', bytes(data)), 0, 32)['status'], 0)
        data = bytearray(fx.ne([(1, icon)]))
        struct.pack_into('<H', data, 0x80 + 2 + 2, 60000)    # resource count far past the table
        self.assertLess(self.extract(self.write('count.exe', bytes(data)), 0, 32)['status'], 0)
        for name, blob in (('f.ico', fx.ico([fx.Image(48, 48, gradient(48, 48, True), bpp=32, alpha=True), *icon])),
                           ('f.exe', fx.pe([('A', icon), (3, icon)])), ('f16.exe', fx.ne([(1, icon), (2, icon)])),
                           ('f.ani', fx.ani([fx.ico(icon, cursor=True)]))):
            path = self.write('fuzz/' + name, blob)
            line = self.run_tool('fuzz', path, 1500)
            self.assertIn('fuzz rounds=1500', line)

    def test_freestanding_core(self):
        """The core links into the Win32 USER DLL: no libc symbol, no float."""
        obj = OUT / 'iconx-w32.obj'
        subprocess.run(['clang', '--target=i686-pc-windows-msvc', '-march=pentiumpro', '-ffreestanding', '-fno-builtin',
                        '-O2', '-Wall', '-Wextra', '-Werror', '-c', str(ROOT / 'apps/libdeskui/iconx.c'), '-o', str(obj)], check=True)
        undefined = subprocess.run(['llvm-nm', '--undefined-only', str(obj)], capture_output=True, text=True, check=True).stdout
        self.assertEqual(undefined.strip(), '')
        listing = subprocess.run(['llvm-objdump', '-d', str(obj)], capture_output=True, text=True, check=True).stdout
        self.assertNotRegex(listing, r'\b(fld|fstp|fild|fmul|movss|movsd|cvtsi2s[sd]|xmm\d)\b')

