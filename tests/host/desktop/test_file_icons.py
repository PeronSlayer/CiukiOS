    def test_pif_and_ini(self):
        r = parse(self.run_tool('pif', self.write('doom.pif', fx.pif('C:\\DOOM\\DOOM.EXE', 'C:\\DOOM\\DOOM.ICO', 1))))
        self.assertEqual((r['status'], r['icon'], r['index'], r['program']), ('1', 'C:\\DOOM\\DOOM.ICO', '1', 'C:\\DOOM\\DOOM.EXE'))
        r = parse(self.run_tool('pif', self.write('default.pif', fx.pif('KEEN.EXE', 'PIFMGR.DLL', 0))))
        self.assertEqual((r['status'], r['icon']), ('0', ''))
        r = parse(self.run_tool('pif', self.write('old.pif', fx.pif('A.COM')[:0x171])))
        self.assertEqual(r['status'], '0')
        self.assertIn('status=-1', self.run_tool('pif', self.write('short.pif', b'\0' * 100)))
        ini = self.write('desktop.ini', b'; comment\r\n[.ShellClassInfo]\r\nIconFile = "Folder.ico" \r\nIconIndex=2\r\n')
        r = parse(self.run_tool('desktopini', ini))
        self.assertEqual((r['status'], r['value'], r['index']), ('1', 'Folder.ico', '2'))
        wide = self.write('wide.ini', b'\xff\xfe' + '[.shellclassinfo]\r\nIconResource=C:\\Icons\\set.dll,-12\r\n'.encode('utf-16-le'))
        r = parse(self.run_tool('desktopini', wide))
        self.assertEqual((r['value'], r['index']), ('C:\\Icons\\set.dll', '-12'))
        autorun = self.write('autorun.inf', b'[AutoRun]\r\nopen=setup.exe\r\nICON=VALVE.ICO\r\n')
        self.assertEqual(parse(self.run_tool('autorun', autorun))['value'], 'VALVE.ICO')
        other = self.write('other.inf', b'[Other]\r\nicon=x.ico\r\n')
        self.assertEqual(parse(self.run_tool('autorun', other))['status'], '0')
        for text, expected in (('a.exe,1', 'file=a.exe index=1'), ('"C:\\b c\\d.dll" , -5', 'file=C:\\b c\\d.dll index=-5'),
                               ('x,y.ico', 'file=x,y.ico index=0'), ('z.ico,99999999999', 'file=z.ico,99999999999 index=0')):
            self.assertIn(expected, self.run_tool('split', text))

