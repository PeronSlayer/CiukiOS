    def test_resolution_on_a_tree(self):
        root, images, other = self.tree()
        try:
            env = {'FILE_ICONS_ROOT': str(root)}
            red32 = fx.fnv(images[1].expected())
            blue32 = fx.fnv(other[0].expected())

            def check(path, own, fallback, fnv=None, file=None, directory=-1, index=None):
                r = parse(self.run_tool('resolve', path, directory, 32, env=env))
                self.assertEqual((r['own'], r['fallback']), (str(own), fallback), path)
                if file:
                    self.assertEqual(r['file'], file, path)
                if index is not None:
                    self.assertEqual(r['index'], str(index), path)
                if fnv is not None:
                    self.assertEqual(r.get('fnv'), f'{fnv:08x}', path)
                elif own == 0:
                    self.assertEqual(r['loaded'], '0', path)
            check('/Q3Ademo/quake3.exe', 1, 'application-x-executable', red32, '/Q3Ademo/quake3.exe')
            menu = '/Windows/Start Menu/Programs/Quake 3 Arena Demo/'
            check(menu + 'quake3.lnk', 1, 'application-x-executable', red32, '/Q3Ademo/quake3.exe')
            check(menu + 'second.lnk', 1, 'application-x-executable', blue32, index=-2)
            check(menu + 'readme.lnk', 0, 'text-x-generic')
            check('/Documents/Desktop/Half-Life.lnk', 1, 'application-x-executable', blue32, '/SIERRA/Half-Life/hl.exe')
            check('/Documents/Desktop/chain.lnk', 1, 'application-x-executable', blue32)
            check('/Documents/Desktop/Games.lnk', 0, 'type:folder')
            check('/Documents/Desktop/Calculator.lnk', 0, 'program:calc')
            check('/Documents/Desktop/Doom.lnk', 0, 'menu:game')
            check('/GAMES/DOOM/doom.pif', 1, 'type:executable', red32, '/GAMES/DOOM/DOOM.ICO')
            check('/GAMES/DOOM/plain.pif', 1, 'type:executable', file='/GAMES/DOOM/DOOM.EXE')   # DOS: no icon
            r = parse(self.run_tool('resolve', '/GAMES/DOOM/plain.pif', -1, 32, env=env))
            self.assertEqual(r['loaded'], '0')
            check('/GAMES/DOOM/DOOM.EXE', 1, 'application-x-executable')
            check('/Documents/site.url', 1, 'program:netsurf', red32)
            check('/Games/Custom', 1, 'type:folder', red32, '/GAMES/DOOM/DOOM.ICO', directory=1)
            check('/Games/Plain', 0, 'type:folder', directory=1)          # writable folder: desktop.ini ignored
            check('/mnt/d', 1, 'type:folder', blue32, directory=1)        # AUTORUN.INF icon=, case-insensitive
            check('/Documents/notes.txt', 0, 'text-x-generic')
            check('/missing/file.exe', 1, 'application-x-executable')
        finally:
            (root / 'Games/Custom').chmod(0o755)

    def test_cache_sync_worker_overlay_and_mtime(self):
        root, images, other = self.tree()
        try:
            env = {'FILE_ICONS_ROOT': str(root)}
            red16, red32 = fx.fnv(images[0].expected()), fx.fnv(images[1].expected())
            readme = '/Windows/Start Menu/Programs/Quake 3 Arena Demo/readme.lnk'
            keys = ['/Q3Ademo/quake3.exe', '/Q3Ademo/quake3.exe|1', '/Documents/notes.txt', '/missing.exe', readme]
            for mode in ('sync', 'worker'):
                out = self.run_tool('cache', mode, *keys, 'link:/Windows/Start Menu/Programs/Quake 3 Arena Demo/quake3.lnk', env=env)
                lines = {line.split(' key=', 1)[1]: parse(line.split(' key=', 1)[0]) for line in out.splitlines() if ' key=' in line}
                self.assertEqual((lines['/Q3Ademo/quake3.exe']['fnv16'], lines['/Q3Ademo/quake3.exe']['fnv32']),
                                 (f'{red16:08x}', f'{red32:08x}'), mode)
                self.assertEqual(lines['/Q3Ademo/quake3.exe|1']['fnv32'], f'{fx.fnv(other[0].expected()):08x}')
                if mode == 'sync':   # the 48 px image the group lacks: the 32 px one scaled up, in line
                    self.assertEqual(lines['/Q3Ademo/quake3.exe']['fnv48'], f'{fx.fnv(fx.area(images[1].expected(), 32, 32, 48)):08x}')
                self.assertEqual([lines[k]['shortcut'] for k in keys], ['0', '0', '0', '0', '1'])
                # Not read (no own icon to find, or missing): the caller draws its default.
                self.assertEqual((lines['/Documents/notes.txt']['own'], lines['/Documents/notes.txt']['fnv32']), ('0', '00000000'))
                self.assertEqual((lines['/missing.exe']['own'], lines['/missing.exe']['fnv32']), ('0', '00000000'))
                # A shortcut read whose target has no icon: the target's type (text-x-generic).
                self.assertEqual((lines[readme]['own'], lines[readme]['fallback']), ('0', 'text-x-generic'))
                self.assertNotEqual(lines[readme]['fnv32'], '00000000')
                link = lines['/Windows/Start Menu/Programs/Quake 3 Arena Demo/quake3.lnk']
                self.assertEqual((link['own'], link['shortcut']), ('1', '1'))
                self.assertNotIn(link['fnv32'], (f'{red32:08x}', '00000000'))         # the overlay is composed
                stats = parse(next(line for line in out.splitlines() if line.startswith('stats')))
                self.assertEqual(stats['refused'], '0')
                if mode == 'worker':
                    self.assertGreaterEqual(int(stats['queued']), 4)
            # A new modification time re-extracts; the same one keeps the cached pixels.
            target = root / 'Q3Ademo/quake3.exe'
            replacement = self.write('replacement.exe', fx.pe([(1, other)]))
            r = parse(self.run_tool('mtime', '/Q3Ademo/quake3.exe', replacement, target, env=env))
            self.assertEqual((r['first'], r['again_same'], r['stale_time']), (f'{red32:08x}', '1', f'{red32:08x}'))
            self.assertEqual((r['second'], r['stale']), (f'{fx.fnv(other[0].expected()):08x}', '1'))
        finally:
            (root / 'Games/Custom').chmod(0o755)

    @unittest.skipUnless(CD.is_dir() and (CD / 'autorun.inf').is_file(), 'the Half-Life CD is not mounted')
    def test_local_half_life_cd(self):
        """Local only: the original CD's AUTORUN.INF names VALVE.ICO; read in place, never copied."""
        env = {'FILE_ICONS_ROOT': str(CD.parent)}
        r = parse(self.run_tool('resolve', '/' + CD.name, 1, 32, env=env))
        # The CD is not at a drive root in this tree: AUTORUN.INF is read for drive roots only.
        self.assertEqual(r['own'], '0')
        env = {'FILE_ICONS_ROOT': str(CD)}
        r = parse(self.run_tool('resolve', '/', 1, 32, env=env))
        self.assertEqual((r['own'], r['file'].lower(), r['loaded']), ('1', '/valve.ico', '1'))
        for name in ('SETUP.EXE', 'autorun.exe'):
            r = parse(self.run_tool('resolve', '/' + name, 0, 32, env=env))
            self.assertEqual(r['own'], '1', name)
            print(f"\n{name}: own icon loaded={r.get('loaded')} fnv={r.get('fnv')}")


