static int fail(const char *key, const char *reason)
{
    fprintf(stderr, "abi layout: FAIL: %s: %s\n", key, reason);
    return 1;
}

int main(int argc, char **argv)
{
    /* The dump is a flat JSON object of unsigned integers. Parse it strictly:
     * reject missing/duplicate/extra keys and trailing data, not just mismatches.
     */
    const size_t count = sizeof(expectations) / sizeof(expectations[0]);
    unsigned char seen[sizeof(expectations) / sizeof(expectations[0])] = {0};
    FILE *input;
    size_t found = 0;
    int c;
    if (argc != 2) return fail("usage", "abi_layout_test target.json");
    input = fopen(argv[1], "r");
    if (!input) return fail(argv[1], "cannot open target dump");
    do { c = fgetc(input); } while (c == ' ' || c == '\n' || c == '\t' || c == '\r');
    if (c != '{') { fclose(input); return fail("JSON", "expected object"); }
    for (;;) {
        char key[160];
        unsigned long long value = 0;
        size_t length = 0, index;
        do { c = fgetc(input); } while (c == ' ' || c == '\n' || c == '\t' || c == '\r');
        if (c != '"') { fclose(input); return fail("JSON", "expected key"); }
        while ((c = fgetc(input)) != '"') {
            if (c < 32 || c == '\\' || length + 1 >= sizeof(key)) {
                fclose(input); return fail("JSON", "invalid key");
            }
            key[length++] = (char)c;
        }
        key[length] = '\0';
        do { c = fgetc(input); } while (c == ' ' || c == '\n' || c == '\t' || c == '\r');
        if (c != ':') { fclose(input); return fail(key, "expected colon"); }
        do { c = fgetc(input); } while (c == ' ' || c == '\n' || c == '\t' || c == '\r');
        if (c < '0' || c > '9') { fclose(input); return fail(key, "expected unsigned value"); }
        do {
            value = value * 10 + (unsigned)(c - '0');
            if (value > UINT32_MAX) { fclose(input); return fail(key, "value overflow"); }
            c = fgetc(input);
        } while (c >= '0' && c <= '9');
        for (index = 0; index < count; ++index)
            if (strcmp(key, expectations[index].key) == 0) break;
        if (index == count) { fclose(input); return fail(key, "unexpected target entry"); }
        if (seen[index]) { fclose(input); return fail(key, "duplicate target entry"); }
        seen[index] = 1;
        ++found;
        int check_native = 1;
#if !defined(__i386__)
        /* Native LP64 objects are not the target C model. Wire-record values
         * are still checked natively; the i686 dump checks target-only keys.
         */
        if (strncmp(key, "target.", 7) == 0) check_native = 0;
#endif
        if (value != expectations[index].expected ||
            (check_native && expectations[index].native != expectations[index].expected)) {
            fprintf(stderr, "abi layout: %s: target=%llu native=%u contract=%u\n",
                    key, value, expectations[index].native, expectations[index].expected);
            fclose(input); return 1;
        }
        while (c == ' ' || c == '\n' || c == '\t' || c == '\r') c = fgetc(input);
        if (c == '}') break;
        if (c != ',') { fclose(input); return fail(key, "expected comma or end"); }
    }
    do { c = fgetc(input); } while (c == ' ' || c == '\n' || c == '\t' || c == '\r');
    if (c != EOF || ferror(input)) { fclose(input); return fail("JSON", "trailing data/read error"); }
    fclose(input);
    for (size_t i = 0; i < count; ++i)
        if (!seen[i]) return fail(expectations[i].key, "missing target entry");
    if (found != count) return fail("JSON", "wrong entry count");

    /* Function/aggregate macros cannot appear in the numeric object table. */
    const struct ciuki_pthread_mutex mutex = CIUKI_PTHREAD_MUTEX_INITIALIZER;
    const struct ciuki_pthread_cond cond = CIUKI_PTHREAD_COND_INITIALIZER;
    for (size_t i = 0; i < 8; ++i)
        if (mutex.words[i] != 0) return fail("mutex initializer", "nonzero word");
    for (size_t i = 0; i < 4; ++i)
        if (cond.words[i] != 0) return fail("condition initializer", "nonzero word");
    if (!WIFEXITED(9472) || WEXITSTATUS(9472) != 37 || WIFSIGNALED(9472) ||
        WIFEXITED(11) || !WIFSIGNALED(11) || WTERMSIG(11) != 11 ||
        CIUKI_SIGBIT(SIGINT) != UINT64_C(2) ||
        CIUKI_SIGBIT(SIGCHLD) != UINT64_C(65536))
        return fail("signal/wait macros", "contract result differs");
    printf("abi layout: PASS (%zu target/native contract checks; off_t=8 time_t=8)\n", count);
    return 0;
}
