"""f4-05: the integer OPL3 synthesizer's tables against their DBOPL formulas.

src/kernel/audio/opl3.c is a C port of DOSBox's DBOPL (GPL-2.0-or-later,
pinned in third_party/vsbhda). DBOPL computes its tables with floating point
at run time; the kernel has no FPU code, so the port carries them as constants
in src/kernel/audio/opl3_tables.h. This test recomputes them with the same
IEEE double formulas (DBOPL.CPP InitTables and Chip::Setup for 48000 Hz) and
requires the header to match exactly. `python3 tests/host/test_opl3_tables.py
--write` regenerates the header.
"""
import math
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / 'src/kernel/audio/opl3_tables.h'
RATE = 48000
OPLRATE = 14318180.0 / 288.0
WAVE_SH = 32 - 10
LFO_SH = WAVE_SH - 10
RATE_SH = 24
RATE_MASK = (1 << RATE_SH) - 1
ENV_EXTRA = 0
ENV_MAX = 511
MUL_SH = 16
ATTACK_SAMPLES = (69, 55, 46, 40, 35, 29, 23, 20, 19, 15, 11, 10, 9)
ENVELOPE_INCREASE = (4, 5, 6, 7, 8, 10, 12, 14, 16, 20, 24, 28, 32)


def envelope_select(val):
    if val < 13 * 4:
        return val & 3, 12 - (val >> 2)
    if val < 15 * 4:
        return val - 12 * 4, 0
    return 12, 0


def tables():
    mul = [int(0.5 + math.pow(2.0, -1.0 + (255 - i * 8) * (1.0 / 256)) * (1 << MUL_SH)) for i in range(384)]
    sine = [int(math.sin((i + 0.5) * (math.pi / 512.0)) * 4084) for i in range(512)]
    exp = [int(0.5 + math.pow(2.0, -1.0 + (255 - i * 8) * (1.0 / 256)) * 4085) for i in range(256)]
    scale = OPLRATE / float(RATE)
    lfo_add = int(0.5 + scale * (1 << LFO_SH))
    freq_scale = int(0.5 + scale * (1 << (WAVE_SH - 1 - 10)))
    linear = []
    for i in range(76):
        index, shift = envelope_select(i)
        linear.append(int(scale * (ENVELOPE_INCREASE[index] << (RATE_SH + ENV_EXTRA - shift - 3))) & 0xFFFFFFFF)
    attack = []
    for i in range(62):
        index, shift = envelope_select(i)
        original = int((ATTACK_SAMPLES[index] << shift) / scale)
        guess = int(scale * (ENVELOPE_INCREASE[index] << (RATE_SH - shift - 3)))
        best_add, best_diff = guess, 1 << 30
        for _ in range(16):
            volume, samples, count = ENV_MAX, 0, 0
            while volume > 0 and samples < original * 2:
                count = (count + guess) & 0xFFFFFFFF
                change = count >> RATE_SH
                count &= RATE_MASK
                if change:
                    volume += (~volume * change) >> 3
                samples += 1
            diff = original - samples
            if abs(diff) < best_diff:
                best_diff, best_add = abs(diff), guess
                if not best_diff:
                    break
            correct = (original - diff) / float(original)
            guess = int(guess * correct)
            if diff < 0:
                guess += 1
        attack.append(best_add & 0xFFFFFFFF)
    attack += [8 << RATE_SH] * 14
    return dict(mul=mul, sine=sine, exp=exp, lfo_add=lfo_add, freq_scale=freq_scale, linear=linear, attack=attack)


def array(ctype, name, values, per_line=12):
    rows = [', '.join(str(v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return f'static const {ctype} {name}[{len(values)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def render():
    t = tables()
    return ('/* Generated by tests/host/test_opl3_tables.py (do not edit): the floating\n'
            ' * point tables of DOSBox DBOPL (InitTables, Chip::Setup at 48000 Hz) as\n'
            ' * integer constants, so the kernel port runs without FPU code.\n'
            ' * Copyright (C) 2002-2021 The DOSBox Team (formulas); GPL-2.0-or-later.\n'
            ' * SPDX-License-Identifier: GPL-2.0-or-later */\n'
            '#ifndef CIUKI_OPL3_TABLES_H\n#define CIUKI_OPL3_TABLES_H\n'
            f'#define OPL3_TABLE_RATE {RATE}u\n'
            f'#define OPL3_LFO_ADD {t["lfo_add"]}u   /* also the noise counter add */\n'
            f'#define OPL3_FREQ_SCALE {t["freq_scale"]}u\n'
            + array('uint16_t', 'opl3_mul_table', t['mul'])
            + array('int16_t', 'opl3_sine_table', t['sine'])
            + array('int16_t', 'opl3_exp_table', t['exp'])
            + array('uint32_t', 'opl3_linear_rates', t['linear'], 8)
            + array('uint32_t', 'opl3_attack_rates', t['attack'], 8)
            + '#endif\n')


class Opl3TableTests(unittest.TestCase):
    def test_header_matches_dbopl_formulas(self):
        self.assertEqual(HEADER.read_text(), render())

    def test_known_values(self):
        t = tables()
        self.assertEqual(t['sine'][0], 12)          # WaveTable[0x200]: sin(0.5*pi/512)*4084 truncated
        self.assertEqual(t['mul'][0], 65359)        # 2^(-1/256) * 65536 rounded
        self.assertEqual(t['attack'][62], 8 << 24)  # instant attack for rates 15
        self.assertTrue(all(0 < v < 1 << 32 for v in t['linear'][4:]))


if __name__ == '__main__':
    if sys.argv[1:] == ['--write']:
        HEADER.write_text(render())
        print(f'wrote {HEADER.relative_to(ROOT)}')
    else:
        unittest.main()
